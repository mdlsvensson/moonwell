func TestSchemaGeneratedMatchesTheObjectMetadata(t *testing.T) {
	files, err := renderSchema(objects.LoadMetadata())
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 7 {
		t.Errorf("the schema has %d files, want 7", len(files))
	}
	committed := testkit.Snapshot(t, filepath.Join(testkit.RepoRoot(t), filepath.FromSlash(schemaDir)))
	var differences []string
	rendered := map[string]bool{}
	for _, file := range files {
		name := strings.TrimPrefix(file.path, schemaDir+"/")
		rendered[name] = true
		if found, there := committed[name]; !there {
			differences = append(differences, "missing: "+file.path)
		} else if string(found) != file.text {
			differences = append(differences, "stale:   "+file.path)
		}
	}
	for name := range committed {
		if !rendered[name] {
			differences = append(differences, "stray:   "+schemaDir+"/"+name)
		}
	}
	slices.Sort(differences)
	if len(differences) > 0 {
		t.Errorf("schema/generated is out of date: run `go run ./tools/gen`.\n%s", strings.Join(differences, "\n"))
	}
}

func TestTheModeWithoutANameWritesTheCommittedSchemaFromTheCommittedMetadata(t *testing.T) {
	c := newFakeCheckout(t)
	c.copyRealFiles("data/metadata.json")
	printed, files, err := c.runGen()
	if err != nil {
		t.Fatal(err)
	}
	wrote := ""
	for _, module := range []string{"Hero", "Unit", "Building", "Item", "Ability", "Buff", "Upgrade"} {
		wrote += "wrote schema/generated/" + module + "Props.pkl\n"
	}
	if printed != wrote {
		t.Errorf("printed %q, want %q", printed, wrote)
	}
	want := withGoMod(map[string]string{"data/metadata.json": string(realFile(t, "data/metadata.json"))})
	for _, name := range generatedNames() {
		want[name] = string(realFile(t, name))
	}
	if got := toTexts(files); !maps.Equal(got, want) {
		t.Errorf("the checkout holds %q, and not all of them as they are committed", slices.Sorted(maps.Keys(got)))
	}
	printed, files, err = c.runGen()
	if err != nil {
		t.Fatalf("the second run: %v", err)
	}
	if printed != "" {
		t.Errorf("the second run printed %q, want nothing", printed)
	}
	if got := toTexts(files); !maps.Equal(got, want) {
		t.Errorf("after the second run the checkout holds %q, and not all of them as they are committed",
			slices.Sorted(maps.Keys(got)))
	}
}

