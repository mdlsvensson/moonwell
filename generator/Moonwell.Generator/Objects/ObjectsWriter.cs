using System.Globalization;
using System.Text;
using ObjectKind = Moonwell.Generator.Objects.Kind;

namespace Moonwell.Generator.Objects;

/// <summary>Writes the C# source of <c>Moonwell.Objects</c>' standard objects and the JSON of their values.</summary>
/// <remarks>
/// <para>
/// A kind base (<c>StandardUnit</c>, <c>StandardHero</c>, <c>StandardItem</c>, ...) carries a property for each field
/// of its kind that every object of the kind can have, except a shared field (<see cref="SharedFields"/>), whose live
/// member reads and puts it; a standard class has a constructor that sets the object's values
/// (<see cref="StandardConstructors"/>) and, for an ability, a property for each of its own fields.
/// Every type name in the source is spelled in full (<c>global::Moonwell.Unit</c>), so that a class named like a
/// namespace part cannot shadow it.
/// </para>
/// </remarks>
public static class ObjectsWriter
{
    private const string Root = "global::Moonwell.Objects";
    private const string Runtime = "global::Moonwell";

    /// <summary>The line that makes CSharp.lua leave a type out of the map's script.</summary>
    private const string Ignore = "/// @CSharpLua.Ignore";

    /// <summary>The first line of every generated C# file.</summary>
    public static string Header(string gameVersion)
    {
        return $"// Generated by Moonwell.Generator from the game's data, game {gameVersion}. Do not edit.\n";
    }

    /// <summary>The name of the kind base: <c>StandardUnit</c>, and <c>StandardHero</c> for the heroes of the unit kind.</summary>
    public static string KindBase(ObjectKind kind, bool hero)
    {
        return "Standard" + (hero ? "Hero" : kind.ToString());
    }

    /// <summary>
    /// The source of a kind base. <c>StandardUnit</c> has the unit fields that are not hero-only; <c>StandardHero</c>
    /// (<paramref name="hero"/>) has every unit field. An ability's own fields (those with a <c>Specific</c> list) are
    /// properties of its standard class, not of <c>StandardAbility</c>, but <c>Set</c> knows their types too.
    /// </summary>
    /// <remarks>
    /// A shared field has no property: the kind base carries a <c>[SharedField]</c> with its rules, and overrides the runtime
    /// class's hooks so that its live member reads and puts the declared value while the object has no handle. Its
    /// <c>Default</c> is the runtime class's, typed as the kind base so that every field of the default object can be read.
    /// <c>StandardHero</c> reads most life, most mana and starting mana as the totals the hero starts with
    /// (<c>HeroTotals</c>), keeps a total put on them apart from the base fields (<c>Totals</c>), and declares no level.
    /// </remarks>
    public static string Kind(ObjectKind kind, IReadOnlyList<Field> fields, bool hero)
    {
        if (hero && kind != ObjectKind.Unit)
        {
            throw new ArgumentException("only the unit kind has a hero base", nameof(hero));
        }

        var name = KindBase(kind, hero);
        var held = new List<Field>();
        var common = new List<Field>();
        var shared = new List<Field>();
        foreach (var field in fields)
        {
            if (field.HeroOnly && !hero)
            {
                continue;
            }

            held.Add(field);
            if (SharedFields.MemberOf(kind, field.Id) != null)
            {
                shared.Add(field);
            }
            else if (field.Specific.Count == 0)
            {
                common.Add(field);
            }
        }

        CheckNames(name, common);
        var text = new StringBuilder();
        text.Append("namespace Moonwell.Objects\n{\n");
        text.Append($"    /// <summary>The fields of {Describe(kind, hero)}, which every standard {Noun(kind, hero)} class has.</summary>\n");
        text.Append($"    {Ignore}\n");
        foreach (var field in shared)
        {
            text.Append($"    {SharedFieldAttribute(field, SharedFields.MemberOf(kind, field.Id)!)}\n");
        }

        text.Append($"    public abstract class {name} : {Runtime}.{(hero ? "Hero" : kind.ToString())}\n    {{\n");
        text.Append("        private static readonly global::System.Collections.Generic.Dictionary<string, global::System.Type> fieldTypes =\n");
        text.Append("            new global::System.Collections.Generic.Dictionary<string, global::System.Type>\n            {\n");
        foreach (var field in held)
        {
            text.Append($"                [{Literal(field.Id)}] = typeof({PropertyType(field)}),\n");
        }

        text.Append("            };\n\n");
        text.Append($"        private {Root}.Declared? declared;\n\n");
        text.Append("        /// <summary>The declared values of this object, created on first use.</summary>\n");
        text.Append($"        protected {Root}.Declared Fields => declared ??= new {Root}.Declared(this);\n\n");
        text.Append("        /// <summary>The values put on this object so far, by field id; the build reads them.</summary>\n");
        text.Append("        internal global::System.Collections.Generic.IReadOnlyDictionary<string, object?> Declared => Fields.Values;\n");
        if (SharedFields.Of(kind).Count > 0)
        {
            AppendSharedMembers(text, name, hero);
        }

        foreach (var field in common)
        {
            text.Append('\n');
            AppendProperty(text, field, "        ");
        }

        text.Append('\n');
        text.Append("        /// <summary>Makes the values of a field that has one for each level, level 1 first.</summary>\n");
        text.Append($"        protected static {Root}.Levels<T> Levels<T>(params T[] values)\n        {{\n");
        text.Append($"            return new {Root}.Levels<T>(values);\n        }}\n\n");
        text.Append("        /// <summary>Makes the values of a field that has one for each level from a formula of the level.</summary>\n");
        text.Append($"        protected static {Root}.Levels<T> PerLevel<T>(global::System.Func<int, T> formula)\n        {{\n");
        text.Append($"            return new {Root}.Levels<T>(formula);\n        }}\n\n");
        text.Append("        /// <summary>Puts a value by its field id; a value of another type than the field holds is an error naming the field.</summary>\n");
        text.Append("        protected void Set(string field, object value)\n        {\n");
        text.Append($"            Fields.Put(field, {Root}.FieldChecks.Value({Literal(name)}, fieldTypes, this, field, value));\n        }}\n\n");
        text.Append("        /// <summary>Puts the value of one level of a field by its field id; a value of another type is an error naming the field.</summary>\n");
        text.Append("        protected void Set(string field, int level, object value)\n        {\n");
        text.Append($"            Fields.PutLevel(field, level, {Root}.FieldChecks.LevelValue({Literal(name)}, fieldTypes, this, field, level, value));\n        }}\n");
        text.Append("    }\n}\n");
        return text.ToString();
    }

    /// <summary>
    /// The source of one group and kind: a class for each standard object in it, ordered by name, nested in static
    /// partial classes of the group and the kind (<c>Human</c>, then <c>Units</c>) in namespace <c>Moonwell.Objects</c>.
    /// The class inherits its kind base (heroes <c>StandardHero</c>), has the object's id in <c>[Standard]</c>, and for
    /// an ability has a property for each field specific to the ability's code. A property cannot be named like its
    /// class, so such a field gets its id appended unless field-names.txt names it (<c>hem1</c> is <c>HealingPercent</c>).
    /// With <paramref name="constructors"/>, a class whose object has values gets a constructor that sets them, before
    /// its properties.
    /// </summary>
    /// <param name="outer">The namespace and the classes the objects are nested in, dotted (<c>Moonwell.Objects.Human.Units</c>).</param>
    /// <param name="classes">The objects and their class names; every class name's outer is <paramref name="outer"/>.</param>
    /// <param name="fields">The fields of the abilities (used only for ability classes).</param>
    /// <param name="constructors">The constructors' lines; null for classes without constructors.</param>
    public static string Group(
        string outer,
        IEnumerable<(StandardObject Object, ClassName Name)> classes,
        IReadOnlyList<Field> fields,
        StandardConstructors? constructors = null)
    {
        var ordered = classes.OrderBy(c => c.Name.Name, StringComparer.Ordinal).ToList();
        var byCode = new Dictionary<string, List<Field>>(StringComparer.Ordinal);
        foreach (var field in fields)
        {
            foreach (var code in field.Specific)
            {
                if (!byCode.TryGetValue(code, out var list))
                {
                    byCode[code] = list = new List<Field>();
                }

                list.Add(field);
            }
        }

        var text = new StringBuilder();
        if (ordered.Exists(c => c.Name.Name.All(ch => char.IsAsciiLetterLower(ch) || char.IsAsciiDigit(ch) || ch == '_')))
        {
            text.Append("#pragma warning disable CS8981 // a type name of lower-case letters only is the id of an object with no name\n\n");
        }

        var containers = new ClassName(outer, "_").Containers;
        text.Append($"namespace {ClassName.Root}\n{{\n");
        for (var c = 0; c < containers.Count; c++)
        {
            var at = new string(' ', 4 * (c + 1));
            text.Append($"{at}/// <summary>{ContainerSummary(containers, c)}</summary>\n");
            text.Append($"{at}{Ignore}\n");
            text.Append($"{at}public static partial class {containers[c]}\n{at}{{\n");
        }

        var indent = new string(' ', 4 * (containers.Count + 1));
        for (var i = 0; i < ordered.Count; i++)
        {
            var (obj, name) = ordered[i];
            if (name.Outer != outer)
            {
                throw new ArgumentException($"{name.FullName} is not in {outer}", nameof(classes));
            }

            if (i > 0)
            {
                text.Append('\n');
            }

            var own = obj.Kind == ObjectKind.Ability && obj.Code != null && byCode.TryGetValue(obj.Code, out var specific)
                ? specific
                : new List<Field>();
            own = own.Select(f => f.Name == name.Name ? f with { Name = f.Name + Capitalize(f.Id) } : f).ToList();
            CheckNames(name.FullName, own);

            text.Append($"{indent}/// <summary>{Xml(Summary(obj))}</summary>\n");
            text.Append($"{indent}{Ignore}\n");
            text.Append($"{indent}[{Root}.Standard({Literal(obj.Id)})]\n");
            text.Append($"{indent}public class {name.Name} : {Root}.{KindBase(obj.Kind, obj.IsHero)}\n{indent}{{\n");
            var lines = constructors?.Lines(obj, own) ?? Array.Empty<string>();
            if (lines.Count > 0)
            {
                text.Append($"{indent}    /// <summary>Makes the object with the values of the base tables, World Editor's Default.</summary>\n");
                text.Append($"{indent}    public {name.Name}()\n{indent}    {{\n");
                foreach (var line in lines)
                {
                    text.Append($"{indent}        {line}\n");
                }

                text.Append($"{indent}    }}\n");
            }

            for (var p = 0; p < own.Count; p++)
            {
                if (p > 0 || lines.Count > 0)
                {
                    text.Append('\n');
                }

                AppendProperty(text, own[p], indent + "    ");
            }

            text.Append($"{indent}}}\n");
        }

        for (var c = containers.Count - 1; c >= 0; c--)
        {
            text.Append(new string(' ', 4 * (c + 1))).Append("}\n");
        }

        text.Append("}\n");
        return text.ToString();
    }

    /// <summary>
    /// The members of a kind base whose kind has shared fields: <c>Default</c> typed as the kind base, the hooks a shared
    /// member reads and puts its declared value through, and for <c>StandardHero</c> the totals of its life and mana.
    /// </summary>
    private static void AppendSharedMembers(StringBuilder text, string name, bool hero)
    {
        var declared = $"{Root}.FieldChecks.Declared(fieldTypes, field, value)";
        if (hero)
        {
            text.Append("\n        /// <summary>The totals of most life, most mana and starting mana the hero's class put by their live names, by field id; the build reads them.</summary>\n");
            text.Append("        internal global::System.Collections.Generic.IReadOnlyDictionary<string, object?> Totals => Fields.Totals;\n");
        }

        text.Append("\n        /// <summary>The default object of the type, as the runtime class gives it, with every field of the kind.</summary>\n");
        text.Append($"        public new {Root}.{name} Default => ({Root}.{name})base.Default;\n\n");
        if (hero)
        {
            text.Append("        /// <summary>A shared field's declared value, which its live member reads with no handle: most life, most mana and starting mana as the totals the hero starts with.</summary>\n");
            text.Append("        protected override T DeclaredValue<T>(string field)\n        {\n");
            text.Append($"            return {Root}.HeroTotals.Read<T>(Fields, this, field);\n        }}\n\n");
            text.Append("        /// <summary>Puts a shared field's value, which its live member does when set with no handle: most life, most mana and starting mana as totals; a hero's level is not declared.</summary>\n");
            text.Append("        protected override void Declare(string field, object value)\n        {\n");
            text.Append("            if (field == \"ulev\")\n            {\n");
            text.Append("                throw new global::System.InvalidOperationException(\"a hero starts at level 1; its level is not declared\");\n            }\n\n");
            text.Append($"            if ({Root}.HeroTotals.Holds(field))\n            {{\n");
            text.Append($"                Fields.PutTotal(field, {declared});\n                return;\n            }}\n\n");
            text.Append($"            Fields.Put(field, {declared});\n        }}\n");
            return;
        }

        text.Append("        /// <summary>A shared field's declared value, which its live member reads with no handle.</summary>\n");
        text.Append("        protected override T DeclaredValue<T>(string field)\n        {\n");
        text.Append("            return Fields.Get<T>(this, field);\n        }\n\n");
        text.Append("        /// <summary>Puts a shared field's value, which its live member does when set with no handle.</summary>\n");
        text.Append("        protected override void Declare(string field, object value)\n        {\n");
        text.Append($"            Fields.Put(field, {declared});\n        }}\n");
    }

    /// <summary>
    /// The <c>[SharedField]</c> of a shared field, with the rules a property of it would carry (<see cref="RuleAttributes"/>):
    /// its label, its range with <c>HasLimits</c>, <c>NonNegative</c> and <c>Required</c>.
    /// </summary>
    /// <exception cref="InvalidOperationException">The field has a rule or a type <c>[SharedField]</c> cannot carry.</exception>
    private static string SharedFieldAttribute(Field field, string member)
    {
        var rules = field.Rules;
        if (rules.MaxLength.HasValue || rules.MaxEntries.HasValue || field.PerLevel || field.Type == FieldType.Choice)
        {
            throw new InvalidOperationException($"shared field {field.Id} has a rule or a type [SharedField] cannot carry");
        }

        var text = new StringBuilder($"[{Root}.SharedField({Literal(field.Id)}, {Literal(member)}");
        if (rules.Label != null)
        {
            text.Append($", Label = {Literal(rules.Label)}");
        }

        if (IsLimited(field))
        {
            text.Append(rules.Min.HasValue ? $", Min = {Number(rules.Min.Value)}" : "");
            text.Append(rules.Max.HasValue ? $", Max = {Number(rules.Max.Value)}" : "");
            text.Append(", HasLimits = true");
        }

        if (IsNumber(field) && rules.NoNegative)
        {
            text.Append(", NonNegative = true");
        }

        if (rules.Required)
        {
            text.Append(", Required = true");
        }

        return text.Append(")]").ToString();
    }

    // "The standard objects of the group Human.", "The standard units of the group Human.", "The standard items."
    private static string ContainerSummary(IReadOnlyList<string> containers, int at)
    {
        if (containers.Count == 1)
        {
            return $"The standard {containers[0].ToLowerInvariant()}.";
        }

        return at == 0
            ? $"The standard objects of the group {containers[0]}."
            : $"The standard {containers[at].ToLowerInvariant()} of the group {containers[0]}.";
    }

    /// <summary>
    /// The source of the enums of the choice types, ordered by name, in namespace <c>Moonwell.Objects</c>. Each member
    /// has the game's text in <c>[GameValue]</c>, then the other spellings the game's data uses; a flags type is a
    /// <c>[Flags]</c> enum. Each enum is <c>@CSharpLua.Ignore</c>: the map's Lua has the members' numbers, not the enum.
    /// A core enum (<see cref="ChoiceType.Core"/>, <c>Moonwell.AttackType</c>) is not written: an internal enum of its
    /// name in the class <c>CoreChoices</c>, after the others, holds the game's texts of its members, the table the build
    /// and <c>StandardValues</c> read them from.
    /// </summary>
    public static string Choices(IEnumerable<ChoiceType> choices)
    {
        var ordered = choices.OrderBy(c => c.Name, StringComparer.Ordinal).ToList();
        var text = new StringBuilder();
        text.Append("namespace Moonwell.Objects\n{\n");
        var first = true;
        foreach (var choice in ordered.Where(c => !c.Core))
        {
            text.Append(first ? "" : "\n");
            first = false;
            text.Append($"    /// <summary>{ChoiceSummary(choice)}</summary>\n");
            text.Append($"    {Ignore}\n");
            if (choice.Flags)
            {
                text.Append("    [global::System.Flags]\n");
            }

            text.Append($"    public enum {choice.Name}\n    {{\n");
            AppendMembers(text, choice, "        ");
            text.Append("    }\n");
        }

        var core = ordered.Where(c => c.Core).ToList();
        if (core.Count > 0)
        {
            text.Append(first ? "" : "\n");
            text.Append("    /// <summary>The game's texts of the members of the choice enums that are core Moonwell's, by the enum's name: the build and StandardValues read them here, and the map's Lua has none of them.</summary>\n");
            text.Append($"    {Ignore}\n");
            text.Append("    internal static class CoreChoices\n    {\n");
            for (var c = 0; c < core.Count; c++)
            {
                var choice = core[c];
                text.Append(c > 0 ? "\n" : "");
                text.Append($"        /// <summary>The game's texts of <see cref=\"{choice.TypeName}\"/>, the metadata type <c>{Xml(choice.Type)}</c>: each member is the core enum's member of its name and number.</summary>\n");
                text.Append($"        internal enum {choice.Name}\n        {{\n");
                AppendMembers(text, choice, "            ");
                text.Append("        }\n");
            }

            text.Append("    }\n");
        }

        text.Append("}\n");
        return text.ToString();
    }

    private static void AppendMembers(StringBuilder text, ChoiceType choice, string indent)
    {
        for (var m = 0; m < choice.Members.Count; m++)
        {
            var member = choice.Members[m];
            var texts = string.Join(", ", new[] { member.Text }.Concat(member.Alternates).Select(Literal));
            text.Append(m > 0 ? "\n" : "");
            text.Append($"{indent}/// <summary>{MemberSummary(choice, member)}</summary>\n");
            text.Append($"{indent}[{Root}.GameValue({texts})]\n");
            text.Append($"{indent}{member.Name} = {member.Value.ToString(CultureInfo.InvariantCulture)},\n");
        }
    }

    // Ruling R15: an enum's numbers are Moonwell's (World Editor's list), not the natives'.
    private const string NotNatives =
        " Its numbers are Moonwell's, from World Editor's list, not the natives' (JASS's ATTACK_TYPE_MAGIC is 4, AttackType.Magic is 6): never cast one to or from a native's value.";

    private static string ChoiceSummary(ChoiceType choice)
    {
        switch (choice.Form)
        {
            case ChoiceForm.List:
                return $"Any of the values of the metadata type <c>{Xml(choice.Type)}</c>, as World Editor offers them; the object file holds a comma list of their texts, and 0 is none of them.{NotNatives}";
            case ChoiceForm.Bits:
                return $"Any of the values of the metadata type <c>{Xml(choice.Type)}</c>, as World Editor offers them; the object file holds the number whose bits they are, and 0 is none of them.{NotNatives}";
            default:
                return $"A value of the metadata type <c>{Xml(choice.Type)}</c>, as World Editor offers it.{NotNatives}";
        }
    }

    private static string MemberSummary(ChoiceType choice, ChoiceMember member)
    {
        var shown = Xml(member.Label.Length > 0 ? member.Label : member.Text) + ".";
        if (choice.Flags && member.Value != 0 && member.Name == "None")
        {
            // Targets.None is World Editor's target "none", one of the values; no flags at all is 0.
            return $"{shown} World Editor's \"{Xml(member.Text)}\", a value of its own: no values at all is 0, not this.";
        }

        return shown;
    }

    /// <summary>
    /// The JSON of a kind's standard values: <c>fields</c> (id, type, perLevel, pointer, skin, store, and for a choice
    /// the enum's name in <c>choice</c>), one per line, then
    /// <c>objects</c> by id, one per line, each with its <c>values</c>, the <c>sets</c> that differ and, only when
    /// there are any, the <c>missingFrom</c> sets. Keys are in ordinal order. A key whose value is the empty string in
    /// a set is a key the set has no value for.
    /// </summary>
    public static string Values(IReadOnlyList<StandardObject> objects, IReadOnlyList<Field> fields)
    {
        var text = new StringBuilder();
        text.Append("{\"fields\":[\n");
        for (var i = 0; i < fields.Count; i++)
        {
            var field = fields[i];
            text.Append("{\"id\":").Append(Json(field.Id));
            text.Append(",\"type\":").Append(Json(TypeName(field.Type)));
            text.Append(",\"perLevel\":").Append(field.PerLevel ? "true" : "false");
            text.Append(",\"pointer\":").Append(field.DataPointer.ToString(CultureInfo.InvariantCulture));
            text.Append(",\"skin\":").Append(field.Skin ? "true" : "false");
            text.Append(",\"store\":").Append(Json(field.Store));
            if (field.Choice != null)
            {
                text.Append(",\"choice\":").Append(Json(field.Choice.Name));
            }

            text.Append(i + 1 < fields.Count ? "},\n" : "}\n");
        }

        text.Append("],\"objects\":{\n");
        var ordered = objects.OrderBy(o => o.Id, StringComparer.Ordinal).ToList();
        for (var i = 0; i < ordered.Count; i++)
        {
            var obj = ordered[i];
            text.Append(Json(obj.Id)).Append(":{\"values\":");
            AppendMap(text, obj.Values);
            text.Append(",\"sets\":{");
            var first = true;
            foreach (var set in obj.Sets.Keys.OrderBy(k => k, StringComparer.Ordinal))
            {
                text.Append(first ? "" : ",").Append(Json(set)).Append(':');
                AppendMap(text, obj.Sets[set]);
                first = false;
            }

            text.Append('}');
            if (obj.MissingFrom.Count > 0)
            {
                text.Append(",\"missingFrom\":[");
                text.Append(string.Join(",", obj.MissingFrom.OrderBy(m => m, StringComparer.Ordinal).Select(Json)));
                text.Append(']');
            }

            text.Append(i + 1 < ordered.Count ? "},\n" : "}\n");
        }

        text.Append("}}\n");
        return text.ToString();
    }

    /// <summary>
    /// The JSON of the gameplay constants: an object of the data sets (<c>base</c>, <c>custom_v0</c>), one per line, each
    /// the constants by key. Sets and keys are in ordinal order.
    /// </summary>
    public static string Misc(IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> sets)
    {
        var text = new StringBuilder("{\n");
        var ordered = sets.Keys.OrderBy(k => k, StringComparer.Ordinal).ToList();
        for (var i = 0; i < ordered.Count; i++)
        {
            text.Append(Json(ordered[i])).Append(':');
            AppendMap(text, sets[ordered[i]]);
            text.Append(i + 1 < ordered.Count ? ",\n" : "\n");
        }

        text.Append("}\n");
        return text.ToString();
    }

    /// <summary>The name of a field type in the values JSON.</summary>
    public static string TypeName(FieldType type)
    {
        var name = type.ToString();
        return char.ToLowerInvariant(name[0]) + name.Substring(1);
    }

    private static void AppendProperty(StringBuilder text, Field field, string indent)
    {
        var id = Literal(field.Id);
        var element = ElementType(field);
        text.Append($"{indent}/// <summary>The field <c>{Xml(field.Id)}</c>.</summary>\n");
        var label = field.Rules.Label == null ? "" : $", Label = {Literal(field.Rules.Label)}";
        text.Append($"{indent}[{Root}.Field({id}{label})]\n");
        foreach (var rule in RuleAttributes(field))
        {
            text.Append(indent).Append(rule).Append('\n');
        }

        text.Append($"{indent}public {PropertyType(field)} {field.Name}\n{indent}{{\n");
        if (field.Type == FieldType.ObjectList)
        {
            text.Append($"{indent}    get {{ return Fields.GetList<{element}>(this, {id}); }}\n");
        }
        else if (field.Type == FieldType.ObjectRef)
        {
            text.Append($"{indent}    get {{ return Fields.GetRef<{element}>({id}); }}\n");
        }
        else
        {
            var get = field.PerLevel ? $"GetLevels<{element}>(this, {id})" : $"Get<{element}>(this, {id})";
            text.Append($"{indent}    get {{ return Fields.{get}; }}\n");
            text.Append($"{indent}    protected set {{ Fields.Put({id}, value); }}\n");
        }

        text.Append($"{indent}}}\n");
    }

    /// <summary>
    /// The rule attributes of a field's property, in this order and only those the field has: <c>[Limits]</c> for a
    /// number field (or a number list held as text) with a <c>minVal</c> or <c>maxVal</c>; <c>[NonNegative]</c> for one
    /// that allows no negative (<see cref="FieldRules.NoNegative"/>); <c>[Required]</c>; <c>[MaxLength]</c>;
    /// <c>[MaxEntries]</c>. A choice has none: its enum is its rule.
    /// </summary>
    private static List<string> RuleAttributes(Field field)
    {
        var rules = field.Rules;
        var attributes = new List<string>();
        if (IsLimited(field))
        {
            attributes.Add(LimitsAttribute(rules.Min, rules.Max));
        }

        if (IsNumber(field) && rules.NoNegative)
        {
            attributes.Add($"[{Root}.NonNegative]");
        }

        if (rules.Required)
        {
            attributes.Add($"[{Root}.Required]");
        }

        if (rules.MaxLength.HasValue)
        {
            attributes.Add($"[{Root}.MaxLength({rules.MaxLength.Value.ToString(CultureInfo.InvariantCulture)})]");
        }

        if (rules.MaxEntries.HasValue)
        {
            attributes.Add($"[{Root}.MaxEntries({rules.MaxEntries.Value.ToString(CultureInfo.InvariantCulture)})]");
        }

        return attributes;
    }

    // A number field, or a number list held as text that has limits: the fields [Limits] and [NonNegative] apply to.
    private static bool IsNumber(Field field)
    {
        var limited = field.Rules.Min.HasValue || field.Rules.Max.HasValue;
        return field.Type == FieldType.Int || field.Type == FieldType.Float || (field.Type == FieldType.String && limited);
    }

    // A number field with a minVal or a maxVal.
    private static bool IsLimited(Field field)
    {
        return IsNumber(field) && (field.Rules.Min.HasValue || field.Rules.Max.HasValue);
    }

    /// <summary>The <c>[Limits]</c> attribute of a range; a missing end is an infinity (<c>double.NegativeInfinity</c>).</summary>
    public static string LimitsAttribute(double? min, double? max)
    {
        var low = min.HasValue ? Number(min.Value) : "double.NegativeInfinity";
        var high = max.HasValue ? Number(max.Value) : "double.PositiveInfinity";
        return $"[{Root}.Limits({low}, {high})]";
    }

    // A limit as C# reads the same double back.
    private static string Number(double value)
    {
        return value.ToString("R", CultureInfo.InvariantCulture);
    }

    /// <summary>The type of a field's value: the object type for a list or a reference, the enum for a choice, else <c>int</c>, <c>float</c>, <c>bool</c> or <c>string</c>.</summary>
    private static string ElementType(Field field)
    {
        switch (field.Type)
        {
            case FieldType.Int:
                return "int";
            case FieldType.Float:
                return "float";
            case FieldType.Bool:
                return "bool";
            case FieldType.String:
                return "string";
            case FieldType.Choice:
                return field.Choice!.TypeName;
            default:
                return field.ListOf == null || field.ListOf == "object" ? "object" : $"{Runtime}.{field.ListOf}";
        }
    }

    /// <summary>The type of a field's property.</summary>
    private static string PropertyType(Field field)
    {
        var element = ElementType(field);
        switch (field.Type)
        {
            case FieldType.ObjectList:
                return $"{Root}.ObjectList<{element}>";
            case FieldType.ObjectRef:
                return $"{Root}.ObjectRef<{element}>";
            default:
                return field.PerLevel ? $"{Root}.Levels<{element}>" : element;
        }
    }

    private static string Capitalize(string text)
    {
        return text.Length == 0 ? text : char.ToUpperInvariant(text[0]) + text.Substring(1);
    }

    private static void CheckNames(string owner, IReadOnlyList<Field> fields)
    {
        var seen = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var field in fields)
        {
            if (!seen.TryAdd(field.Name, field.Id))
            {
                throw new InvalidOperationException($"{owner}: fields {seen[field.Name]} and {field.Id} are both named {field.Name}");
            }
        }
    }

    private static string Describe(ObjectKind kind, bool hero)
    {
        var noun = Noun(kind, hero);
        // "unit" starts with a vowel but is said with a consonant.
        return ("aeiou".Contains(noun[0]) && !noun.StartsWith("uni", StringComparison.Ordinal) ? "an " : "a ") + noun;
    }

    private static string Noun(ObjectKind kind, bool hero)
    {
        return hero ? "hero" : kind.ToString().ToLowerInvariant();
    }

    // "Paladin (Hpal).", with an editor suffix "Shockwave (Cairne), AOs2." (decision 71), and "spur." for no name.
    private static string Summary(StandardObject obj)
    {
        var suffix = obj.EditorSuffix.Trim();
        if (suffix.Length > 0)
        {
            return obj.Name.Length == 0 ? $"{suffix}, {obj.Id}." : $"{obj.Name} {suffix}, {obj.Id}.";
        }

        return obj.Name.Length == 0 ? obj.Id + "." : $"{obj.Name} ({obj.Id}).";
    }

    /// <summary>Text for an XML doc comment on one line.</summary>
    private static string Xml(string text)
    {
        var line = new StringBuilder();
        foreach (var c in text)
        {
            switch (c)
            {
                case '&':
                    line.Append("&amp;");
                    break;
                case '<':
                    line.Append("&lt;");
                    break;
                case '>':
                    line.Append("&gt;");
                    break;
                case '\r':
                case '\n':
                case '\t':
                    line.Append(' ');
                    break;
                default:
                    line.Append(c);
                    break;
            }
        }

        return line.ToString();
    }

    /// <summary>A C# string literal.</summary>
    private static string Literal(string text)
    {
        return "\"" + text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
    }

    private static void AppendMap(StringBuilder text, IReadOnlyDictionary<string, string> map)
    {
        text.Append('{');
        var first = true;
        foreach (var key in map.Keys.OrderBy(k => k, StringComparer.Ordinal))
        {
            text.Append(first ? "" : ",").Append(Json(key)).Append(':').Append(Json(map[key]));
            first = false;
        }

        text.Append('}');
    }

    /// <summary>A JSON string.</summary>
    private static string Json(string text)
    {
        var json = new StringBuilder("\"");
        foreach (var c in text)
        {
            switch (c)
            {
                case '"':
                    json.Append("\\\"");
                    break;
                case '\\':
                    json.Append("\\\\");
                    break;
                case '\n':
                    json.Append("\\n");
                    break;
                case '\r':
                    json.Append("\\r");
                    break;
                case '\t':
                    json.Append("\\t");
                    break;
                default:
                    if (c < ' ')
                    {
                        json.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        json.Append(c);
                    }

                    break;
            }
        }

        return json.Append('"').ToString();
    }
