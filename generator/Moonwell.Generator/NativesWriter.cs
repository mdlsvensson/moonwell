using System.Globalization;
using System.Text;

namespace Moonwell.Generator;

public static class NativesWriter
{
    public const string Namespace = "Moonwell";

    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
        "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
        "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof",
        "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint",
        "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    };

    private static readonly HashSet<string> CallbacksReturningBool = new(StringComparer.Ordinal) { "Condition", "Filter" };

    public static string Header(string gameVersion) =>
        $"// Generated by Moonwell.Generator from the game's common.j and blizzard.j, game {gameVersion}. Do not edit.\n";

    public static string WriteTypes(JassScripts scripts, string gameVersion)
    {
        var text = new StringBuilder(Header(gameVersion));
        text.Append($"\nnamespace {Namespace}\n{{\n");
        text.Append("    /// @CSharpLua.Ignore\n    public class handle\n    {\n        internal handle() { }\n    }\n");
        foreach (var type in scripts.Types)
        {
            var name = Identifier(type.Name);
            text.Append($"\n    /// @CSharpLua.Ignore\n    public class {name} : {Identifier(type.Parent)}\n    {{\n        internal {name}() {{ }}\n    }}\n");
        }

        text.Append("}\n");
        return text.ToString();
    }

    public static string WriteLuaTypes(JassScripts scripts, string gameVersion)
    {
        var text = new StringBuilder(Header(gameVersion).Replace("//", "--"));
        text.Append("do\nlocal define = System.define\n");
        text.Append($"local {LuaLocal("handle")} = define(\"{Namespace}.handle\", {{}})\n");
        var defined = new HashSet<string> { "handle" };
        var pending = new List<JassType>(scripts.Types);
        while (pending.Count > 0)
        {
            var ready = pending.Where(t => defined.Contains(t.Parent)).ToList();
            if (ready.Count == 0)
            {
                throw new InvalidOperationException($"types with unknown parents: {string.Join(", ", pending.Select(t => t.Name))}");
            }

            foreach (var type in ready)
            {
                text.Append($"local {LuaLocal(type.Name)} = define(\"{Namespace}.{type.Name}\", {{ base = {{ {LuaLocal(type.Parent)} }} }})\n");
                defined.Add(type.Name);
                pending.Remove(type);
            }
        }

        text.Append("end\n");
        return text.ToString();
    }

    public static string WriteNatives(JassScripts scripts, string gameVersion)
    {
        var text = new StringBuilder(Header(gameVersion));
        text.Append($"\nusing System;\n\nnamespace {Namespace}\n{{\n");
        text.Append("    /// @CSharpLua.Ignore\n    public static class Natives\n    {\n");

        var constants = new HashSet<string>(StringComparer.Ordinal);
        foreach (var global in scripts.Globals)
        {
            WriteGlobal(text, global, constants);
        }

        foreach (var function in scripts.Functions)
        {
            WriteFunction(text, function);
        }

        text.Append("    }\n}\n");
        return text.ToString();
    }

    private static void WriteFunction(StringBuilder text, JassFunction function)
    {
        var parameters = string.Join(", ", function.Parameters.Select(p =>
            $"{CsType(p.Type, function.Name)} {Identifier(p.Name)}"));
        var arguments = string.Join(", ", function.Parameters.Select((_, i) => $"{{{i}}}"));
        text.Append($"\n        /// @CSharpLua.Template = \"{function.Name}({arguments})\"\n");
        text.Append($"        public static extern {CsType(function.Returns, function.Name)} {Identifier(function.Name)}({parameters});\n");
    }

    private static void WriteGlobal(StringBuilder text, JassGlobal global, HashSet<string> constants)
    {
        var type = CsType(global.Type, global.Name);
        var name = Identifier(global.Name);
        if (global.IsArray)
        {
            text.Append($"\n        /// @CSharpLua.Template = \"{global.Name}[{{0}}]\"\n");
            text.Append($"        public static extern {type} {name}(int index);\n");
            return;
        }

        if (global.IsConstant && ConstantValue(global, constants) is { } value)
        {
            constants.Add(global.Name);
            text.Append($"\n        public const {type} {name} = {value};\n");
            return;
        }

        text.Append($"\n        /// @CSharpLua.Get = \"{global.Name}\"\n");
        if (!global.IsConstant)
        {
            text.Append($"        /// @CSharpLua.Set = \"{global.Name} = {{0}}\"\n");
        }

        var accessors = global.IsConstant ? "get;" : "get; set;";
        text.Append($"        public static extern {type} {name} {{ {accessors} }}\n");
    }

    public static string? ConstantValue(JassGlobal global, IReadOnlySet<string> constants)
    {
        var value = global.Value;
        if (value is null)
        {
            return null;
        }

        if (constants.Contains(value))
        {
            return Identifier(value);
        }

        switch (global.Type)
        {
            case "integer":
                return IntegerLiteral(value)?.ToString(CultureInfo.InvariantCulture);
            case "real":
                return RealLiteral(value);
            case "boolean":
                return value is "true" or "false" ? value : null;
            case "string":
                return value.Length >= 2 && value[0] == '"' && value[^1] == '"' ? value : null;
            default:
                return null;
        }
    }

    public static int? IntegerLiteral(string value)
    {
        var negative = value.StartsWith('-');
        var digits = negative ? value[1..].Trim() : value;
        long? result = null;
        if (digits.Length is 3 or 6 && digits[0] == '\'' && digits[^1] == '\'')
        {
            result = digits[1..^1].Aggregate(0L, (sum, c) => sum * 256 + c);
        }
        else if (digits.StartsWith("0x", StringComparison.OrdinalIgnoreCase) || digits.StartsWith('$'))
        {
            var hex = digits.StartsWith('$') ? digits[1..] : digits[2..];
            if (long.TryParse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var parsed))
            {
                result = parsed;
            }
        }
        else if (long.TryParse(digits, NumberStyles.None, CultureInfo.InvariantCulture, out var parsed))
        {
            result = parsed;
        }

        if (result is null)
        {
            return null;
        }

        return unchecked((int)(negative ? -result.Value : result.Value));
    }

    private static string? RealLiteral(string value)
    {
        if (!double.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var parsed))
        {
            return IntegerLiteral(value) is { } whole ? $"{whole}f" : null;
        }

        return parsed.ToString("R", CultureInfo.InvariantCulture) + "f";
    }

    public static string CsType(string jassType, string owner) => jassType switch
    {
        "integer" => "int",
        "real" => "float",
        "boolean" => "bool",
        "string" => "string",
        "nothing" => "void",
        "code" => CallbacksReturningBool.Contains(owner) ? "Func<bool>" : "Action",
        _ => Identifier(jassType),
    };

    public static string Identifier(string name) => Keywords.Contains(name) ? "@" + name : name;

    private static string LuaLocal(string name) => "t_" + name;
}
