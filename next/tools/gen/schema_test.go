// field is an int field of the stats category; change adjusts it.
func field(id, name string, change func(*objects.FieldMeta)) objects.FieldMeta {
	meta := objects.FieldMeta{
		ID: id, Name: name, Label: name, Category: "stats", Type: "int", Storage: "int",
		Use: []string{}, Specific: []string{}, NotSpecific: []string{},
	}
	if change != nil {
		change(&meta)
	}
	return meta
}

func typed(fieldType, storage string) func(*objects.FieldMeta) {
	return func(meta *objects.FieldMeta) { meta.Type, meta.Storage = fieldType, storage }
}

func used(use ...string) func(*objects.FieldMeta) {
	return func(meta *objects.FieldMeta) { meta.Use = use }
}

func labelled(label string) func(*objects.FieldMeta) {
	return func(meta *objects.FieldMeta) { meta.Label = label }
}

// metadataWith is the metadata of game 1.2.3.4 with the fields, by the list they are in, and no standard object.
func metadataWith(fields map[string][]objects.FieldMeta) *objects.Metadata {
	metadata := &objects.Metadata{
		Format: 1,
		Game:   "1.2.3.4",
		Fields: map[string][]objects.FieldMeta{},
		Bases:  map[manifest.Category]map[string]objects.BaseMeta{},
	}
	for _, list := range objects.FieldLists {
		metadata.Fields[list] = fields[list]
	}
	return metadata
}

// metadataOfOneBuff is the text of a data/metadata.json whose one field is an int field of buffs with the id and
// the name.
func metadataOfOneBuff(t testing.TB, id, name string) string {
	t.Helper()
	return metadataText(t, map[string][]objects.FieldMeta{"buffs": {field(id, name, nil)}})
}

// metadataText is the text of a data/metadata.json of game 1.2.3.4 with the fields, by the list they are in.
func metadataText(t testing.TB, fields map[string][]objects.FieldMeta) string {
	t.Helper()
	text, err := json.Marshal(metadataWith(fields))
	if err != nil {
		t.Fatal(err)
	}
	return string(text)
}

// schema renders the schema and returns each module's text by its name ("Hero", "Unit", ...).
func schema(t *testing.T, fields map[string][]objects.FieldMeta) map[string]string {
	t.Helper()
	files, err := renderSchema(metadataWith(fields))
	if err != nil {
		t.Fatal(err)
	}
	modules := map[string]string{}
	for _, file := range files {
		modules[strings.TrimSuffix(strings.TrimPrefix(file.path, "schema/generated/"), "Props.pkl")] = file.text
	}
	return modules
}

var propertyLine = regexp.MustCompile(`(?m)^(\w+): `)

func propertyNames(module string) []string {
	var names []string
	for _, match := range propertyLine.FindAllStringSubmatch(module, -1) {
		names = append(names, match[1])
	}
	return names
}

// generatedNames is the paths of the seven files of the schema, sorted.
func generatedNames() []string {
	var names []string
	for _, name := range []string{"Ability", "Buff", "Building", "Hero", "Item", "Unit", "Upgrade"} {
		names = append(names, "schema/generated/"+name+"Props.pkl")
	}
	return names
}

func TestRenderSchemaRendersOneAbstractModulePerObjectClass(t *testing.T) {
	files, err := renderSchema(metadataWith(nil))
	if err != nil {
		t.Fatal(err)
	}
	var paths []string
	for _, file := range files {
		paths = append(paths, file.path)
	}
	slices.Sort(paths)
	if !slices.Equal(paths, generatedNames()) {
		t.Errorf("paths: %q", paths)
	}
	// The dash of the first line is an em dash.
	const hero = "// GENERATED by `go run ./tools/gen` from data/metadata.json (game 1.2.3.4) \xE2\x80\x94 " +
		"do not edit.\n" +
		"\n" +
		"/// The typed properties of `Hero.pkl`: the fields of heroes, named after their World Editor labels.\n" +
		"abstract module moonwell.generated.HeroProps\n" +
		"\n" +
		"extends \"../objects/Object.pkl\"\n"
	if got := schema(t, nil)["Hero"]; got != hero {
		t.Errorf("the module of a category without a field is %q, want %q", got, hero)
	}
	contains(t, schema(t, nil)["Ability"],
		"/// The typed properties of `Ability.pkl`: the ability fields not specific to one base ability, named after")
}

// The modules stand in the order of the categories, and every category has one.
func TestRenderSchemaRendersTheModulesInTheOrderOfTheCategories(t *testing.T) {
	files, err := renderSchema(metadataWith(nil))
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != len(manifest.Categories) {
		t.Fatalf("%d modules for %d categories", len(files), len(manifest.Categories))
	}
	for i, category := range manifest.Categories {
		what := "the fields of " + string(category) + ","
		if category == "abilities" {
			what = "the ability fields not specific to one base ability,"
		}
		if !strings.Contains(files[i].text, what) {
			t.Errorf("module %d (%s) is not the one of %s", i, files[i].path, category)
		}
	}
}

func TestRenderSchemaTypesEachFieldByStorageListAndLevel(t *testing.T) {
	perLevel := func(inner func(*objects.FieldMeta)) func(*objects.FieldMeta) {
		return func(meta *objects.FieldMeta) {
			if inner != nil {
				inner(meta)
			}
			meta.PerLevel = true
		}
	}
	list := func(fieldType string) func(*objects.FieldMeta) {
		return func(meta *objects.FieldMeta) { meta.Type, meta.Storage, meta.List = fieldType, "string", true }
	}
	ability := schema(t, map[string][]objects.FieldMeta{"abilities": {
		field("aint", "anInt", nil),
		field("abol", "aBool", typed("bool", "int")),
		field("arel", "aReal", typed("real", "real")),
		field("aunr", "anUnreal", typed("unreal", "unreal")),
		field("astr", "aString", typed("string", "string")),
		field("alst", "aList", list("unitList")),
		field("alvi", "levelInt", perLevel(func(meta *objects.FieldMeta) { meta.Column = 1 })),
		field("alvb", "levelBool", perLevel(typed("bool", "int"))),
		field("alvr", "levelReal", perLevel(typed("unreal", "unreal"))),
		field("alvs", "levelString", perLevel(typed("string", "string"))),
		field("alvl", "levelList", perLevel(list("targetList"))),
		field("aenu", "anEnum", typed("attackBits", "int")),
		// A bool is a Boolean only where it is stored as an int: its storage types it otherwise.
		field("abor", "boolAsReal", typed("bool", "real")),
		field("abou", "boolAsUnreal", typed("bool", "unreal")),
		field("abos", "boolAsString", typed("bool", "string")),
		field("alor", "levelBoolAsReal", perLevel(typed("bool", "real"))),
	}})["Ability"]
	for _, line := range []string{
		"boolAsReal: Number?",
		"boolAsUnreal: Number?",
		"boolAsString: String?",
		"levelBoolAsReal: (Number|List<Number>)?",
		"anInt: Int?",
		"aBool: Boolean?",
		"aReal: Number?",
		"anUnreal: Number?",
		"aString: String?",
		"aList: (String|List<String>)?",
		"levelInt: (Int|List<Int>)?",
		"levelBool: (Boolean|List<Boolean>)?",
		"levelReal: (Number|List<Number>)?",
		"levelString: (String|List<String>)?",
		"levelList: (String|List<String>|List<List<String>>)?",
		"anEnum: Int?",
	} {
		contains(t, ability, "\n"+line+"\n")
	}
}

