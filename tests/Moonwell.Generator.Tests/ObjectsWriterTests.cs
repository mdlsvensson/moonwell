            false,
            null,
            new Dictionary<string, string> { ["uhpm"] = "10", ["unam"] = "A \"quoted\" \\ name\n" },
            new Dictionary<string, IReadOnlyDictionary<string, string>>
            {
                ["custom_v1"] = new Dictionary<string, string> { ["uhpm"] = "", ["unam"] = "x" },
                ["melee_v0"] = new Dictionary<string, string>(),
            },
            new[] { "base", "custom_v0" });
        var plain = only with { Id = "hfoo", MissingFrom = Array.Empty<string>() };

