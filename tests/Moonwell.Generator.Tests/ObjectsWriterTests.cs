    /// <summary>Compiles Moonwell.Objects' Core folder and the sources with the settings of the project (C# 13, nullable) and lists what it reports.</summary>
    private static List<string> Compile(IEnumerable<string> sources)
    {
        var options = new CSharpParseOptions(LanguageVersion.CSharp13);
        var trees = new List<SyntaxTree>();
        foreach (var path in Directory.GetFiles(Path.Combine(RepositoryRoot(), "src", "Moonwell.Objects", "Core"), "*.cs"))
        {
            trees.Add(CSharpSyntaxTree.ParseText(File.ReadAllText(path), options, path));
        }

        foreach (var source in sources)
        {
            trees.Add(CSharpSyntaxTree.ParseText(source, options, $"Generated{trees.Count}.g.cs"));
        }

        var references = new List<MetadataReference>();
        foreach (var path in ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator))
        {
            if (!Path.GetFileName(path).StartsWith("Moonwell", StringComparison.Ordinal))
            {
                references.Add(MetadataReference.CreateFromFile(path));
            }
        }

        references.Add(MetadataReference.CreateFromFile(Path.Combine(AppContext.BaseDirectory, "Moonwell.dll")));
        references.Add(MetadataReference.CreateFromFile(Path.Combine(AppContext.BaseDirectory, "Moonwell.Natives.dll")));
        var compilation = CSharpCompilation.Create(
            "Moonwell.Objects",
            trees,
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        return compilation.GetDiagnostics()
            .Where(d => d.Severity >= DiagnosticSeverity.Warning)
            .Select(d => d.ToString())
            .ToList();
    }

    private static string Class(string source, string name)
    {
        var start = source.IndexOf($" class {name} ", StringComparison.Ordinal);
        Assert.True(start >= 0, $"no class {name} in:\n{source}");
        var lineStart = source.LastIndexOf('\n', start) + 1;
        var indent = new string(' ', source.Substring(lineStart).TakeWhile(ch => ch == ' ').Count());
        var end = source.IndexOf("\n" + indent + "}\n", start, StringComparison.Ordinal);
        return source.Substring(start, end + 1 - start);
    }

