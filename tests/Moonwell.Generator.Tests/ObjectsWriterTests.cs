    [Fact]
    public void values_json_round_trips()
    {
        var tables = MiniExport();
        var fields = Fields.Of(tables, Kind.Unit);
        var objects = StandardObjects.Of(tables, Kind.Unit, fields);

        var json = ObjectsWriter.Values(objects, fields);

        using var document = JsonDocument.Parse(json);
        var listed = document.RootElement.GetProperty("fields");
        Assert.Equal(fields.Count, listed.GetArrayLength());
        for (var i = 0; i < fields.Count; i++)
        {
            var field = listed[i];
            Assert.Equal(fields[i].Id, field.GetProperty("id").GetString());
            Assert.Equal(ObjectsWriter.TypeName(fields[i].Type), field.GetProperty("type").GetString());
            Assert.Equal(fields[i].PerLevel, field.GetProperty("perLevel").GetBoolean());
            Assert.Equal(fields[i].DataPointer, field.GetProperty("pointer").GetInt32());
            Assert.Equal(fields[i].Skin, field.GetProperty("skin").GetBoolean());
            Assert.Equal(fields[i].Store, field.GetProperty("store").GetString());
        }

        var parsed = document.RootElement.GetProperty("objects");
        Assert.Equal(objects.Count, parsed.EnumerateObject().Count());
        foreach (var expected in objects)
        {
            var actual = parsed.GetProperty(expected.Id);
            var values = actual.GetProperty("values").EnumerateObject().ToDictionary(p => p.Name, p => p.Value.GetString()!);
            Assert.Equal(expected.Values.OrderBy(p => p.Key, StringComparer.Ordinal), values.OrderBy(p => p.Key, StringComparer.Ordinal));
            var sets = actual.GetProperty("sets").EnumerateObject().ToDictionary(
                p => p.Name,
                p => p.Value.EnumerateObject().ToDictionary(v => v.Name, v => v.Value.GetString()!));
            Assert.Equal(expected.Sets.Keys.OrderBy(k => k, StringComparer.Ordinal), sets.Keys.OrderBy(k => k, StringComparer.Ordinal));
            foreach (var set in expected.Sets)
            {
                Assert.Equal(set.Value.OrderBy(p => p.Key, StringComparer.Ordinal), sets[set.Key].OrderBy(p => p.Key, StringComparer.Ordinal));
            }

            Assert.Equal(expected.MissingFrom.Count > 0, actual.TryGetProperty("missingFrom", out var missing));
            if (expected.MissingFrom.Count > 0)
            {
                Assert.Equal(expected.MissingFrom.OrderBy(m => m, StringComparer.Ordinal), missing.EnumerateArray().Select(m => m.GetString()));
            }
        }
    }

    [Fact]
    public void values_json_keeps_missing_sets_blanks_and_base()
    {
        var field = new Field(Kind.Unit, "uhpm", "HitPoints", FieldType.Int, null, false, 0, false, Array.Empty<string>(), "HP");
        var only = new StandardObject(
            Kind.Unit,
            "spur",
            "",
            "",
