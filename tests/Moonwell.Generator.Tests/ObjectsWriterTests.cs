        Assert.Equal(new[] { "base", "custom_v0" }, spur.GetProperty("missingFrom").EnumerateArray().Select(m => m.GetString()));
        Assert.False(document.RootElement.GetProperty("objects").GetProperty("hfoo").TryGetProperty("missingFrom", out _));
    }

    [Fact]
    public void values_json_is_one_field_and_one_object_a_line_in_ordinal_order()
    {
        var tables = MiniExport();
        var fields = Fields.Of(tables, Kind.Unit);
        var objects = StandardObjects.Of(tables, Kind.Unit, fields);

        var lines = ObjectsWriter.Values(objects.Reverse().ToList(), fields).Split('\n');

        Assert.Equal("{\"fields\":[", lines[0]);
        Assert.StartsWith("{\"id\":\"ides\",\"type\":\"string\",\"perLevel\":false,\"pointer\":0,\"skin\":", lines[1]);
        Assert.Equal("],\"objects\":{", lines[1 + fields.Count]);
        Assert.StartsWith("\"Hpal\":{\"values\":{", lines[2 + fields.Count]);
        Assert.StartsWith("\"hfoo\":{\"values\":{", lines[3 + fields.Count]);
        Assert.Equal("}}", lines[4 + fields.Count]);
        Assert.Equal("", lines[5 + fields.Count]);
        var keys = JsonDocument.Parse("{" + lines[2 + fields.Count].TrimEnd(',') + "}")
            .RootElement.GetProperty("Hpal").GetProperty("values").EnumerateObject().Select(p => p.Name).ToList();
        Assert.Equal(keys.OrderBy(k => k, StringComparer.Ordinal), keys);
    }

