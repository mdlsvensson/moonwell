func TestEveryKeywordOfLuaIsNoNameOfAParameter(t *testing.T) {
	keywords := []string{
		"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto", "if", "in", "local", "nil",
		"not", "or", "repeat", "return", "then", "true", "until", "while",
	}
	var params []script.NativeParam
	for _, keyword := range keywords {
		params = append(params, script.NativeParam{Name: keyword, Type: "integer"})
	}
	params = append(params, script.NativeParam{Name: "endX", Type: "integer"}, script.NativeParam{Name: "End", Type: "integer"})
	declared := renderNatives(&script.Natives{Functions: []script.NativeFunction{{Name: "F", Params: params, Returns: "nothing"}}})
	checkContains(t, declared, "function F("+strings.Join(keywords, "_, ")+"_, endX, End) end\n")
	for _, keyword := range keywords {
		checkContains(t, declared, "---@param "+keyword+"_ integer\n")
	}
}

func TestTheHandleClassesAreDeclaredParentsFirstAndSiblingsInByteOrder(t *testing.T) {
	n := &script.Natives{Types: []script.NativeType{
		{Name: "widget", Extends: "agent"}, {Name: "b" + beyond, Extends: "handle"}, {Name: "b" + fullWidthA, Extends: "handle"},
		{Name: "agent", Extends: "handle"}, {Name: "Zed", Extends: "handle"}, {Name: "orphan", Extends: "nowhere"},
		{Name: "ability", Extends: "agent"},
	}}
	want := []string{
		"---@class handle", "---@class Zed: handle", "---@class agent: handle", "---@class ability: agent",
		"---@class widget: agent", "---@class b" + fullWidthA + ": handle", "---@class b" + beyond + ": handle",
	}
	declared := renderNatives(n)
	if _, classes, found := strings.Cut(declared, "do not edit.\n\n"); !found || classes != strings.Join(want, "\n")+"\n" {
		t.Errorf("renderNatives =\n%s", declared)
	}
}

func TestTheRuntimeDeclarationsDeclareTheModulesHooksAndRequire(t *testing.T) {
	declarations := runtimeDeclarations
	if !strings.HasPrefix(declarations, "---@meta moonwell\n") || !strings.HasSuffix(declarations, "\nreturn moonwell\n") {
		t.Errorf("runtimeDeclarations =\n%s", declarations)
	}
	for _, hook := range []string{"before_config", "on_config", "before_main", "on_main"} {
		checkContains(t, declarations, "---@param fn fun(): ...\nfunction moonwell."+hook+"(fn) end\n")
	}
	checkContains(t, declarations, "function moonwell.format_error(message) end\n",
		"---@param name string\n---@return any\nfunction require(name) end\n")
	for number, line := range strings.Split(strings.TrimSuffix(declarations, "\n"), "\n") {
		isComment := strings.HasPrefix(line, "---") || strings.HasPrefix(line, "-- ")
		isStatement := line == "local moonwell = {}" || line == "return moonwell" ||
			strings.HasPrefix(line, "function ") && strings.HasSuffix(line, ") end")
		if line != "" && !isComment && !isStatement {
			t.Errorf("line %d of the runtime declarations is neither a comment nor a statement: %q", number+1, line)
		}
	}
}

func testObjects() []objects.Resolved {
	return []objects.Resolved{
		{Category: "units", Key: "captain", ID: "h000"},
		{Category: "units", Key: "archer", ID: "h001"},
		{Category: "abilities", Key: "holyLight", ID: "A000"},
	}
}

func TestTheObjectDeclarationsDeclareEveryCategoryKeysSortedWithRawcodes(t *testing.T) {
	declarations := renderObjects(testObjects())
	if !strings.HasPrefix(declarations, "---@meta generated.objects\n---@diagnostic disable: missing-fields\n") {
		t.Errorf("renderObjects =\n%s", declarations)
	}
	checkContains(t, declarations,
		"---@class generated.objects.units\n---@field archer integer h001\n---@field captain integer h000\n",
		"---@class generated.objects.heroes\n\n",
		"---@type generated.objects.abilities\nobjects.abilities = {}\n",
		"return objects\n")
	if got := strings.Count(declarations, "---@class "); got != len(manifest.Categories) {
		t.Errorf("%d classes for %d categories", got, len(manifest.Categories))
	}
}

func TestTheObjectDeclarationsOfNoObjectsDeclareEveryCategoryEmpty(t *testing.T) {
	want := "---@meta generated.objects\n---@diagnostic disable: missing-fields\n" +
		"-- GENERATED by Moonwell from objects/**.pkl; do not edit.\n\n"
	for _, category := range manifest.Categories {
		want += "---@class generated.objects." + string(category) + "\n\n"
	}
	want += "local objects = {}\n\n"
	for _, category := range manifest.Categories {
		want += "---@type generated.objects." + string(category) + "\nobjects." + string(category) + " = {}\n\n"
	}
	want += "return objects\n"
	if got := renderObjects(nil); got != want {
		t.Errorf("renderObjects(nil) =\n%s", got)
	}
}

func TestTheObjectDeclarationsSortKeysByBytesAndKeepTheOrderOfEqualOnes(t *testing.T) {
	declarations := renderObjects([]objects.Resolved{
		{Category: "items", Key: "k" + beyond, ID: "I000"}, {Category: "items", Key: "k" + fullWidthA, ID: "I001"},
		{Category: "items", Key: "same", ID: "I002"}, {Category: "items", Key: "Zed", ID: "I003"},
		{Category: "items", Key: "same", ID: "I004"}, {Category: "items", Key: "_low", ID: "I005"},
	})
	checkContains(t, declarations, "---@class generated.objects.items\n"+
		"---@field Zed integer I003\n---@field _low integer I005\n"+
		"---@field k"+fullWidthA+" integer I001\n---@field k"+beyond+" integer I000\n"+
		"---@field same integer I002\n---@field same integer I004\n\n")
}

