func testNatives() *script.Natives {
	n := &script.Natives{
		GameVersion: "9.9.9",
		Types:       []script.NativeType{{Name: "agent", Extends: "handle"}, {Name: "unit", Extends: "widget"}, {Name: "widget", Extends: "agent"}},
		Functions: []script.NativeFunction{
			{
				Name: "CreateThing", Source: "common.j", Returns: "unit",
				Params: []script.NativeParam{{Name: "id", Type: "player"}, {Name: "end", Type: "real"}, {Name: "cb", Type: "code"}},
			},
			{Name: "DoNothing", Source: "blizzard.j", Returns: "nothing"},
			{Name: "FourCC", Source: "lua", Params: []script.NativeParam{{Name: "id", Type: "string"}}, Returns: "integer"},
		},
		Globals: []script.NativeGlobal{
			{Name: "MAX_THINGS", Source: "common.j", Type: "integer", Constant: true},
			{Name: "counts", Source: "blizzard.j", Type: "real", Array: true},
		},
	}
	n.Lua.Globals, n.Lua.Removed = []string{"print"}, []string{"io"}
	return n
}

func TestJASSTypesMapToLuaTypesHandleTypesKeepTheirNames(t *testing.T) {
	for jass, want := range map[string]string{
		"integer": "integer", "real": "number", "boolean": "boolean", "string": "string", "code": "function",
		"handle": "handle", "unit": "unit", "any": "any", "": "",
	} {
		if got := luaType(jass); got != want {
			t.Errorf("luaType(%q) = %q, want %q", jass, got, want)
		}
	}
}

