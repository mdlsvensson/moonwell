var luaTypes = map[string]string{
	"integer": "integer",
	"real":    "number",
	"boolean": "boolean",
	"string":  "string",
	"code":    "function",
}

var luaKeywords = []string{
	"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto", "if", "in", "local", "nil", "not",
	"or", "repeat", "return", "then", "true", "until", "while",
}

// LuaType is the lua-language-server type for a JASS type. Handle types, and the Lua types of the Lua-only
// functions, pass through.
func LuaType(jassType string) string {
	if luaType, ok := luaTypes[jassType]; ok {
		return luaType
	}
	return jassType
}

// paramName is a JASS parameter name as a Lua identifier: a Lua keyword gets a trailing underscore.
func paramName(name string) string {
	if slices.Contains(luaKeywords, name) {
		return name + "_"
	}
	return name
}

// classLines declares the handle classes, each after its parent, starting from `handle` (which no `type` line
// declares).
func classLines(n *natives.Natives) []string {
	children := map[string][]string{}
	for _, handleType := range n.Types {
		children[handleType.Extends] = append(children[handleType.Extends], handleType.Name)
	}
	lines := []string{"---@class handle"}
	var visit func(parent string)
	visit = func(parent string) {
		names := slices.Clone(children[parent])
		text.Sort(names)
		for _, name := range names {
			lines = append(lines, "---@class "+name+": "+parent)
			visit(name)
		}
	}
	visit("handle")
	return lines
}

// RenderNatives is .moonwell/types/natives.d.lua.
func RenderNatives(n *natives.Natives) string {
	out := []string{
		"---@meta",
		"-- GENERATED by Moonwell from Warcraft III " + n.GameVersion + " (common.j, blizzard.j); do not edit.",
		"",
	}
	out = append(out, classLines(n)...)
	out = append(out, "")
	for _, function := range n.Functions {
		params := make([]string, len(function.Params))
		for i, param := range function.Params {
			params[i] = paramName(param.Name)
			out = append(out, "---@param "+params[i]+" "+LuaType(param.Type))
		}
		if function.Returns != "nothing" {
			out = append(out, "---@return "+LuaType(function.Returns))
		}
		out = append(out, "function "+function.Name+"("+strings.Join(params, ", ")+") end", "")
	}
	for _, global := range n.Globals {
		array := ""
		if global.Array {
			array = "[]"
		}
		out = append(out, "---@type "+LuaType(global.Type)+array, global.Name+" = nil", "")
	}
	return strings.Join(out, "\n")
}

