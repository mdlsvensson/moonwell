// RenderObjects is .moonwell/types/objects.d.lua: src/generated/objects.yue as gameplay code sees it.
func RenderObjects(resolved []objects.Resolved) string {
	out := []string{
		"---@meta generated.objects",
		// `objects.units = {}` below would otherwise warn that the class's fields are missing.
		"---@diagnostic disable: missing-fields",
		"-- GENERATED by Moonwell from objects/**.pkl; do not edit.",
		"",
	}
	for _, category := range objects.Categories {
		out = append(out, "---@class generated.objects."+string(category))
		var entries []objects.Resolved
		for _, object := range resolved {
			if object.Category == category {
				entries = append(entries, object)
			}
		}
		slices.SortStableFunc(entries, func(a, b objects.Resolved) int { return text.Compare(a.Key, b.Key) })
		for _, object := range entries {
			out = append(out, "---@field "+object.Key+" integer "+object.ID)
		}
		out = append(out, "")
	}
	out = append(out, "local objects = {}", "")
	for _, category := range objects.Categories {
		out = append(out, "---@type generated.objects."+string(category), "objects."+string(category)+" = {}", "")
	}
	out = append(out, "return objects", "")
	return strings.Join(out, "\n")
}

// RenderMap is .moonwell/types/map.d.lua. source is the war3map.lua the globals came from, as the project names it;
// globals is nil when there is no such file.
func RenderMap(globals *luasrc.MapGlobals, source string) string {
	if globals == nil {
		return "---@meta\n-- GENERATED by Moonwell: there is no " + source + " yet; save the map in World Editor.\n"
	}
	out := []string{"---@meta", "-- GENERATED by Moonwell from " + source + "; do not edit.", ""}
	for _, global := range globals.Globals {
		out = append(out, "---@type "+global.Type, global.Name+" = nil", "")
	}
	for _, function := range globals.Functions {
		out = append(out, "function "+function+"() end", "")
	}
	return strings.Join(out, "\n")
}
