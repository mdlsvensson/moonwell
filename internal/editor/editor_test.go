func TestTheTemplatesLuarcIndexesTheCompiledLuaFilesAndSuggestsEveryGameGlobal(t *testing.T) {
	config := templateLuarc(t)
	if useGitIgnore, _ := config.Get("workspace.useGitIgnore"); useGitIgnore != false {
		t.Errorf("workspace.useGitIgnore = %v", useGitIgnore)
	}
	// The library view in .moonwell/lua is what the editor should see; the copies it is made from are not workspace
	// files.
	if !slices.Contains(listOf(t, config, "workspace.ignoreDir"), ".moonwell/libraries") {
		t.Error("workspace.ignoreDir lacks .moonwell/libraries")
	}
	// The YueScript extension asks for completion at a placeholder word, so the typed prefix never narrows the list:
	// lua-language-server must be allowed to suggest every native and game global at once.
	api := natives.Load()
	names := len(api.Functions) + len(api.Globals)
	if limit, _ := config.Get("completion.maxSuggestCount"); limit == nil || limit.(float64) < float64(names) {
		t.Errorf("completion.maxSuggestCount %v < %d names", limit, names)
	}
}

