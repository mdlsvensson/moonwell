// templateLuarc is the embedded template's .luarc.json.
func templateLuarc(t *testing.T) *ordered.Object {
	t.Helper()
	template, err := moonwell.TemplateFiles()
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range template {
		if file.Path == ".luarc.json" {
			tree, err := ordered.Decode(file.Data)
			if err != nil {
				t.Fatal(err)
			}
			return tree.(*ordered.Object)
		}
	}
	t.Fatal("the template has no .luarc.json")
	return nil
}

func listOf(t *testing.T, config *ordered.Object, key string) []string {
	t.Helper()
	value, _ := config.Get(key)
	list, ok := value.([]any)
	if !ok {
		t.Fatalf("%s is %v, not an array", key, value)
	}
	names := make([]string, len(list))
	for i, entry := range list {
		names[i], _ = entry.(string)
	}
	return names
}

func decode(t *testing.T, text string) *ordered.Object {
	t.Helper()
	tree, err := ordered.Decode([]byte(text))
	if err != nil {
		t.Fatal(err)
	}
	return tree.(*ordered.Object)
}

