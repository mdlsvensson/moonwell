func TestRefreshWritesTheDeclarationsAndTheMacroModuleThenOnlyWhatChanged(t *testing.T) {
	root := t.TempDir()
	testkit.WriteFile(t, root, "maps/map.w3x/war3map.lua", []byte("udg_Score = 0\nfunction main()\nend\n"))
	written, err := editor.Refresh(root, inputs())
	want := []string{
		".moonwell/types/natives.d.lua",
		".moonwell/types/moonwell.d.lua",
		".moonwell/types/objects.d.lua",
		".moonwell/types/map.d.lua",
		".moonwell/yue/moonwell/macros.yue",
	}
	if err != nil || !slices.Equal(written, want) {
		t.Fatalf("Refresh = %q, %v", written, err)
	}
	if read(t, root, ".moonwell/yue/moonwell/macros.yue") != moonwell.MacrosYue || read(t, root, ".moonwell/types/moonwell.d.lua") != editor.RuntimeDeclarations {
		t.Error("the macro module or the runtime declarations differ from the embedded ones")
	}
	contains(t, read(t, root, ".moonwell/types/map.d.lua"), "udg_Score = nil")
	if written, err := editor.Refresh(root, inputs()); err != nil || len(written) != 0 {
		t.Errorf("unchanged, but Refresh = %q, %v", written, err)
	}
	testkit.WriteFile(t, root, "maps/map.w3x/war3map.lua", []byte("udg_Other = 0\n"))
	if written, err := editor.Refresh(root, inputs()); err != nil || !slices.Equal(written, []string{".moonwell/types/map.d.lua"}) {
		t.Errorf("after a change to the map, Refresh = %q, %v", written, err)
	}
}

