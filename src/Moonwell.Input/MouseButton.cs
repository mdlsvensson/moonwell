namespace Moonwell
{
    /// <summary>A button of a mouse. The numbers are Moonwell's own, not the game's: the game's handle ids differ from common.j's (right was seen as 4, not 3).</summary>
    public enum MouseButton
    {
        /// <summary>The left button.</summary>
        Left = 1,

        /// <summary>The middle button, the wheel pressed.</summary>
        Middle = 2,

        /// <summary>The right button.</summary>
        Right = 3,
    }
}
