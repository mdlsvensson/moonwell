using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace Moonwell.Analyzers;

/// <summary>Rejects the C# that CSharp.lua drops, stops on or writes wrong, so the editor and dotnet build show it with its line.</summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class LuaAnalyzer : DiagnosticAnalyzer
{
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => Rules.Lua;

    public override void Initialize(AnalysisContext context)
    {
        // CSharp.lua compiles a map file that looks generated (Hud.g.cs, an <auto-generated> header) like any other.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterSyntaxNodeAction(Using, SyntaxKind.UsingDirective);
        context.RegisterSyntaxNodeAction(Invocation, SyntaxKind.InvocationExpression);
        context.RegisterSyntaxNodeAction(Joined, SyntaxKind.AddExpression);
        context.RegisterSyntaxNodeAction(JoinedByAssignment, SyntaxKind.AddAssignmentExpression);
        context.RegisterSyntaxNodeAction(Interpolated, SyntaxKind.Interpolation);
        context.RegisterOperationAction(HandleConversion, OperationKind.Conversion);
        context.RegisterOperationAction(HandleIsType, OperationKind.IsType);
        context.RegisterOperationAction(HandlePattern, OperationKind.DeclarationPattern, OperationKind.TypePattern, OperationKind.RecursivePattern);
        context.RegisterSyntaxNodeAction(HandleLoop, SyntaxKind.ForEachStatement);
    }

    // The methods of System.Enum that read an enum's names or members from its type.
    private static readonly ImmutableHashSet<string> TypeMethods = ImmutableHashSet.Create(
        "GetValues", "GetValuesAsUnderlyingType", "GetNames", "GetName", "IsDefined", "Parse", "TryParse", "Format", "ToObject");

    /// <summary>MW0010: an enum of Moonwell.Objects is ignored by CSharp.lua, so the game's Lua has no names or type of it.</summary>
    private static void Invocation(SyntaxNodeAnalysisContext context)
    {
        var invocation = (InvocationExpressionSyntax)context.Node;
        if (context.SemanticModel.GetSymbolInfo(invocation, context.CancellationToken).Symbol is not IMethodSymbol method)
        {
            return;
        }

        if (HandleSequence(context, invocation, method))
        {
            return;
        }

        if (method.Name == "ToString" && !method.IsStatic && ToStringReceiver(invocation) is var (receiver, reported))
        {
            var type = Choice(context.SemanticModel.GetTypeInfo(receiver, context.CancellationToken).Type);
            if (type != null)
            {
                Report(context, reported, type);
                return;
            }
        }

        if (method.IsStatic && method.ContainingType?.SpecialType == SpecialType.System_Enum && TypeMethods.Contains(method.Name))
        {
            var choice = method.TypeArguments.Select(Choice).FirstOrDefault(type => type != null);
            foreach (var argument in invocation.ArgumentList.Arguments)
            {
                if (choice != null)
                {
                    break;
                }

                choice = Choice(argument.Expression is TypeOfExpressionSyntax typeOf
                    ? context.SemanticModel.GetTypeInfo(typeOf.Type, context.CancellationToken).Type
                    : context.SemanticModel.GetTypeInfo(argument.Expression, context.CancellationToken).Type);
            }

            if (choice != null)
            {
                Report(context, invocation, choice);
                return;
            }
        }

        Boxed(context, invocation, method);
    }

    // The receiver of a ToString call and the node to report: x.ToString() and x?.ToString(), where the receiver is the conditional access's.
    private static (ExpressionSyntax Receiver, SyntaxNode Reported)? ToStringReceiver(InvocationExpressionSyntax invocation)
    {
        if (invocation.Expression is MemberAccessExpressionSyntax access)
        {
            return (access.Expression, invocation);
        }

        if (invocation.Expression is MemberBindingExpressionSyntax && invocation.Parent is ConditionalAccessExpressionSyntax conditional
            && conditional.WhenNotNull == invocation)
        {
            return (conditional.Expression, conditional);
        }

        return null;
    }

    // string.Format("{0}", choice), string.Concat("a", choice), builder.Append(choice): an enum given to an object parameter is
    // made into text by the callee's ToString. Equals compares and shows nothing.
    private static void Boxed(SyntaxNodeAnalysisContext context, InvocationExpressionSyntax invocation, IMethodSymbol method)
    {
        if (method.Name is "Equals" or "ReferenceEquals")
        {
            return;
        }

        foreach (var argument in invocation.ArgumentList.Arguments)
        {
            var info = context.SemanticModel.GetTypeInfo(argument.Expression, context.CancellationToken);
            var type = Choice(info.Type);
            if (type != null && info.ConvertedType?.SpecialType == SpecialType.System_Object)
            {
                Report(context, argument.Expression, type);
            }
        }
    }

    // "attack " + unit.AttackType: the string is made with the enum's ToString.
    private static void Joined(SyntaxNodeAnalysisContext context)
    {
        var add = (BinaryExpressionSyntax)context.Node;
        if (context.SemanticModel.GetTypeInfo(add, context.CancellationToken).Type?.SpecialType != SpecialType.System_String)
        {
            return;
        }

        foreach (var side in new[] { add.Left, add.Right })
        {
            var type = Choice(context.SemanticModel.GetTypeInfo(side, context.CancellationToken).Type);
            if (type != null)
            {
                Report(context, side, type);
            }
        }
    }

    // text += choice
    private static void JoinedByAssignment(SyntaxNodeAnalysisContext context)
    {
        var assignment = (AssignmentExpressionSyntax)context.Node;
        if (context.SemanticModel.GetTypeInfo(assignment.Left, context.CancellationToken).Type?.SpecialType != SpecialType.System_String)
        {
            return;
        }

        var type = Choice(context.SemanticModel.GetTypeInfo(assignment.Right, context.CancellationToken).Type);
        if (type != null)
        {
            Report(context, assignment.Right, type);
        }
    }

    private static void Interpolated(SyntaxNodeAnalysisContext context)
    {
        var hole = (InterpolationSyntax)context.Node;
        var type = Choice(context.SemanticModel.GetTypeInfo(hole.Expression, context.CancellationToken).Type);
        if (type != null)
        {
            Report(context, hole, type);
        }
    }

    private static void Report(SyntaxNodeAnalysisContext context, SyntaxNode node, ITypeSymbol choice)
    {
        context.ReportDiagnostic(Diagnostic.Create(Rules.ChoiceNames, node.GetLocation(), node.ToString(), choice.Name));
    }

    // The enum of namespace Moonwell.Objects a type is, or the enum under a nullable of it: a choice of World Editor's, which CSharp.lua ignores.
    private static INamedTypeSymbol? Choice(ITypeSymbol? type)
    {
        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable)
        {
            type = nullable.TypeArguments[0];
        }

        return type is INamedTypeSymbol
        {
            TypeKind: TypeKind.Enum,
            ContainingNamespace: { Name: "Objects", ContainingNamespace: { Name: "Moonwell", ContainingNamespace.IsGlobalNamespace: true } },
        } choice ? choice : null;
    }

    /// <summary>MW0035: a cast or as to a handle type the value is not known to be, which CSharp.lua checks against a class the game's handles do not have.</summary>
    private static void HandleConversion(OperationAnalysisContext context)
    {
        var conversion = (IConversionOperation)context.Operation;
        if (!conversion.Conversion.IsImplicit && conversion.Operand.Type != null && IsHandle(conversion.Type))
        {
            ReportHandle(context, conversion.Type!);
        }
    }

    /// <summary>
    /// MW0035: OfType&lt;T&gt;() of a handle type T, which tests each item with is, and Cast&lt;T&gt;() of one unless the
    /// items already are T, which casts each item (CoreSystem's Linq hands the source back only when it is an IEnumerable&lt;T&gt;).
    /// </summary>
    private static bool HandleSequence(SyntaxNodeAnalysisContext context, InvocationExpressionSyntax invocation, IMethodSymbol method)
    {
        var reduced = method.ReducedFrom ?? method;
        if (reduced is not { Name: "OfType" or "Cast", ContainingType: { Name: "Enumerable", ContainingNamespace: { Name: "Linq" } } }
            || method.TypeArguments.Length != 1 || !IsHandle(method.TypeArguments[0]))
        {
            return false;
        }

        var target = method.TypeArguments[0];
        if (reduced.Name == "Cast")
        {
            var source = invocation.Expression is MemberAccessExpressionSyntax access
                ? context.SemanticModel.GetTypeInfo(access.Expression, context.CancellationToken).Type
                : invocation.ArgumentList.Arguments.FirstOrDefault() is { } first ? context.SemanticModel.GetTypeInfo(first.Expression, context.CancellationToken).Type : null;
            if (ItemType(source) is { } item && SymbolEqualityComparer.Default.Equals(item, target))
            {
                return false;
            }
        }

        context.ReportDiagnostic(Diagnostic.Create(Rules.HandleCheck, invocation.GetLocation(), invocation.ToString(), target.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)));
        return true;
    }

    // The T of the IEnumerable<T> a type is or implements; null for none.
    private static ITypeSymbol? ItemType(ITypeSymbol? type)
    {
        if (type is IArrayTypeSymbol array)
        {
            return array.ElementType;
        }

        if (type is not INamedTypeSymbol named)
        {
            return null;
        }

        foreach (var face in new[] { named }.Concat(named.AllInterfaces))
        {
            if (face is { Name: "IEnumerable", IsGenericType: true, ContainingNamespace: { Name: "Generic" } })
            {
                return face.TypeArguments[0];
            }
        }

        return null;
    }

    /// <summary>MW0035: foreach (unit u in widgets), whose loop casts each item to a handle type it is not known to be.</summary>
    private static void HandleLoop(SyntaxNodeAnalysisContext context)
    {
        var loop = (ForEachStatementSyntax)context.Node;
        var info = context.SemanticModel.GetForEachStatementInfo(loop);
        var variable = context.SemanticModel.GetTypeInfo(loop.Type, context.CancellationToken).Type;
        if (variable == null || !IsHandle(variable) || info.ElementType == null || info.ElementConversion.IsImplicit || info.ElementConversion.IsIdentity)
        {
            return;
        }

        var span = Microsoft.CodeAnalysis.Text.TextSpan.FromBounds(loop.Type.SpanStart, loop.Identifier.Span.End);
        context.ReportDiagnostic(Diagnostic.Create(Rules.HandleCheck, Location.Create(loop.SyntaxTree, span),
            loop.SyntaxTree.GetText(context.CancellationToken).ToString(span), variable.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)));
    }

    /// <summary>MW0035: x is T for a handle type T that x is not known to be.</summary>
    private static void HandleIsType(OperationAnalysisContext context)
    {
        var test = (IIsTypeOperation)context.Operation;
        if (IsHandle(test.TypeOperand) && Checks(context, test.ValueOperand.Type, test.TypeOperand))
        {
            ReportHandle(context, test.TypeOperand);
        }
    }

    /// <summary>MW0035: a type, declaration or recursive pattern of a handle type that the value is not known to be.</summary>
    private static void HandlePattern(OperationAnalysisContext context)
    {
        var pattern = (IPatternOperation)context.Operation;
        var matched = pattern switch
        {
            IDeclarationPatternOperation declaration => declaration.MatchedType,
            ITypePatternOperation type => type.MatchedType,
            IRecursivePatternOperation recursive => recursive.MatchedType,
            _ => null,
        };
        if (IsHandle(matched) && Checks(context, pattern.InputType, matched!))
        {
            ReportHandle(context, matched!);
        }
    }

    // Whether testing a value of one type for another checks its class: not when every value of it already is one (unit is widget).
    private static bool Checks(OperationAnalysisContext context, ITypeSymbol? from, ITypeSymbol to)
    {
        return from != null && !context.Compilation.ClassifyCommonConversion(from, to).IsImplicit;
    }

    private static void ReportHandle(OperationAnalysisContext context, ITypeSymbol checkedType)
    {
        var syntax = context.Operation.Syntax;
        context.ReportDiagnostic(Diagnostic.Create(Rules.HandleCheck, syntax.GetLocation(), syntax.ToString(), checkedType.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)));
    }

    // Whether a type is Moonwell.handle or a class deriving from it, or a type parameter limited to one.
    private static bool IsHandle(ITypeSymbol? type)
    {
        if (type is ITypeParameterSymbol parameter)
        {
            return parameter.ConstraintTypes.Any(IsHandle);
        }

        for (var current = type; current != null; current = current.BaseType)
        {
            if (current is { Name: "handle", ContainingNamespace: { Name: "Moonwell", ContainingNamespace.IsGlobalNamespace: true } })
            {
                return true;
            }
        }

        return false;
    }

    private static void Using(SyntaxNodeAnalysisContext context)
    {
        var directive = (UsingDirectiveSyntax)context.Node;
        if (directive.StaticKeyword.IsKind(SyntaxKind.None) || directive.Name == null)
        {
            return;
        }

        var imported = context.SemanticModel.GetSymbolInfo(directive.Name, context.CancellationToken).Symbol;
        if (imported is INamedTypeSymbol { Name: "Natives", ContainingNamespace: { Name: "Moonwell", ContainingNamespace.IsGlobalNamespace: true } })
        {
            context.ReportDiagnostic(Diagnostic.Create(Rules.StaticNatives, directive.GetLocation()));
        }
    }
}
