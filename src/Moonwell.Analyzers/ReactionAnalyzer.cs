using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Moonwell.Analyzers;

/// <summary>
/// MW0036: a reaction of a package's interface (damage, mouse) the package would never call. The interfaces give every
/// reaction an empty default body, so the compiler takes a misspelt, non-public or wrongly typed reaction without a
/// word, while the package finds a class's reactions by name and calls only the interface's own. MW0041: a reaction of
/// a Moonwell class written without override, or a method with a reaction's name and other parameters, which Moonwell
/// never calls either. It does nothing in a map without Moonwell.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class ReactionAnalyzer : DiagnosticAnalyzer
{
    /// <summary>The names Moonwell 0.3 gave the reactions it renamed, by interface.</summary>
    private static readonly ImmutableDictionary<string, ImmutableDictionary<string, string>> Renamed =
        ImmutableDictionary.CreateRange(new[]
        {
            new KeyValuePair<string, ImmutableDictionary<string, string>>("IDamageSource", ImmutableDictionary<string, string>.Empty),
            new KeyValuePair<string, ImmutableDictionary<string, string>>("IDamageTarget", ImmutableDictionary.CreateRange(new[]
            {
                new KeyValuePair<string, string>("OnLethal", "OnDying"),
            })),
            new KeyValuePair<string, ImmutableDictionary<string, string>>("IDamageWatch", ImmutableDictionary.CreateRange(new[]
            {
                new KeyValuePair<string, string>("OnBeforeArmor", "OnUnitTaking"),
                new KeyValuePair<string, string>("OnAfterArmor", "OnUnitTaken"),
                new KeyValuePair<string, string>("OnLethal", "OnUnitDying"),
                new KeyValuePair<string, string>("OnLanded", "OnUnitHurt"),
                new KeyValuePair<string, string>("OnBurst", "OnUnitBurst"),
            })),
        });

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => Rules.Reactions;

    public override void Initialize(AnalysisContext context)
    {
        // CSharp.lua compiles a map file that looks generated (Hud.g.cs, an <auto-generated> header) like any other.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(start =>
        {
            var compilation = start.Compilation;
            var unit = compilation.GetTypeByMetadataName("Moonwell.Unit");
            var unitComponent = compilation.GetTypeByMetadataName("Moonwell.UnitComponent");
            var mapComponent = compilation.GetTypeByMetadataName("Moonwell.MapComponent");
            if (unit == null || unitComponent == null || mapComponent == null)
            {
                return;
            }

            var families = new List<Family>();
            var unitHosts = new Func<INamedTypeSymbol, bool>(type => IsA(type, unit) || IsA(type, unitComponent));
            var mapHosts = new Func<INamedTypeSymbol, bool>(type => IsA(type, mapComponent));
            const string UnitHosts = "a unit's class and its components (buffs too)";
            const string MapHosts = "the game's and players' components";
            foreach (var name in new[] { "IDamageSource", "IDamageTarget", "IDamageWatch" })
            {
                if (compilation.GetTypeByMetadataName("Moonwell." + name) is { } face)
                {
                    var watch = name == "IDamageWatch";
                    families.Add(new Family(face, "damage package", watch ? mapHosts : unitHosts, watch ? MapHosts : UnitHosts, Renamed[name],
                        method => method.Parameters.Length == 1 && IsDamageParameter(method.Parameters[0].Type), false));
                }
            }

            if (compilation.GetTypeByMetadataName("Moonwell.IMouseWatch") is { } mouse)
            {
                families.Add(new Family(mouse, "input package", mapHosts, MapHosts, ImmutableDictionary<string, string>.Empty,
                    method => method.Parameters.Length is 1 or 2 && method.Parameters[0].Type is { Name: "Mouse" } first
                        && first.ContainingNamespace?.ToDisplayString() == "Moonwell", true));
            }

            var checker = new Checker(families, unit, unitComponent, mapComponent);
            start.RegisterSymbolAction(checker.Check, SymbolKind.NamedType);
            start.RegisterSymbolAction(checker.CheckHidden, SymbolKind.Method);
        });
    }

    /// <summary>Whether a type is the damage package's Hit or Burst.</summary>
    private static bool IsDamageParameter(ITypeSymbol type)
    {
        return type.ContainingNamespace?.ToDisplayString() == "Moonwell" && (type.Name == "Hit" || type.Name == "Burst");
    }

    /// <summary>Whether a type is a class or derives from it.</summary>
    private static bool IsA(INamedTypeSymbol type, INamedTypeSymbol baseType)
    {
        for (INamedTypeSymbol? current = type; current != null; current = current.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(current.OriginalDefinition, baseType))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// A package's interface of reactions: the classes it is called on, the reactions it renamed, the parameters a
    /// reaction takes (for a slip in a name), and whether the game's Lua calls a method of a reaction's name that .NET
    /// does not (an explicit implementation, or one with other parameters), so that the two disagree.
    /// </summary>
    private sealed class Family
    {
        public Family(INamedTypeSymbol face, string package, Func<INamedTypeSymbol, bool> hosts, string hostsText,
            ImmutableDictionary<string, string> renamed, Func<IMethodSymbol, bool> shaped, bool luaByName)
        {
            Interface = face;
            Package = package;
            Hosts = hosts;
            HostsText = hostsText;
            RenamedNames = renamed;
            Shaped = shaped;
            LuaByName = luaByName;
        }

        public INamedTypeSymbol Interface { get; }

        public string Package { get; }

        public Func<INamedTypeSymbol, bool> Hosts { get; }

        public string HostsText { get; }

        public ImmutableDictionary<string, string> RenamedNames { get; }

        /// <summary>Whether a method has the shape of one of this interface's reactions: the parameters they take, for a slip in a name.</summary>
        public Func<IMethodSymbol, bool> Shaped { get; }

        public bool LuaByName { get; }

        /// <summary>The reaction methods of the interface.</summary>
        public IEnumerable<IMethodSymbol> Reactions => Interface.GetMembers().OfType<IMethodSymbol>().Where(m => m.MethodKind == MethodKind.Ordinary);
    }

    /// <summary>The checks of one compilation, with Moonwell's types found once.</summary>
    private sealed class Checker
    {
        private readonly List<Family> families;
        private readonly INamedTypeSymbol unit;
        private readonly INamedTypeSymbol unitComponent;
        private readonly INamedTypeSymbol mapComponent;

        public Checker(List<Family> families, INamedTypeSymbol unit, INamedTypeSymbol unitComponent, INamedTypeSymbol mapComponent)
        {
            this.families = families;
            this.unit = unit;
            this.unitComponent = unitComponent;
            this.mapComponent = mapComponent;
        }

        /// <summary>Checks a class that implements a reaction interface, or is a unit or a component (which might have forgotten one).</summary>
        public void Check(SymbolAnalysisContext context)
        {
            if (context.Symbol is not INamedTypeSymbol { TypeKind: TypeKind.Class } type)
            {
                return;
            }

            var implemented = families.Where(f => type.AllInterfaces.Contains(f.Interface, SymbolEqualityComparer.Default)).ToList();
            if (implemented.Count == 0 && !IsA(type, unit) && !IsA(type, unitComponent) && !IsA(type, mapComponent))
            {
                return;
            }

            CheckHosts(context, type);
            foreach (var method in type.GetMembers().OfType<IMethodSymbol>())
            {
                if (method.IsImplicitlyDeclared || method.IsOverride || !method.Locations.Any(location => location.IsInSource))
                {
                    continue;
                }

                if (method.MethodKind == MethodKind.ExplicitInterfaceImplementation)
                {
                    foreach (var reaction in method.ExplicitInterfaceImplementations)
                    {
                        if (families.FirstOrDefault(f => SymbolEqualityComparer.Default.Equals(f.Interface, reaction.ContainingType)) is { } family)
                        {
                            Report(context, method, reaction.Name, family.LuaByName
                                ? "runs in the game's Lua but not on .NET, where the " + family.Package + " calls only public methods; write it as public void " + reaction.Name + "(...)"
                                : "never runs: the " + family.Package + " calls only public methods, so write it as public void " + reaction.Name + "(...)");
                            break;
                        }
                    }

                    continue;
                }

                if (method.MethodKind != MethodKind.Ordinary || Implements(type, implemented, method))
                {
                    continue;
                }

                var why = Why(type, method, implemented);
                if (why != null)
                {
                    Report(context, method, method.Name, why);
                }
            }
        }

        /// <summary>Why a method that implements no reaction looks like one; null when it does not.</summary>
        private string? Why(INamedTypeSymbol type, IMethodSymbol method, List<Family> implemented)
        {
            var name = method.Name;
            foreach (var family in implemented)
            {
                var reaction = family.Reactions.FirstOrDefault(r => r.Name == name);
                if (reaction == null)
                {
                    continue;
                }

                // Written right, yet not the implementation: the class gets the interface from a base class, whose mapping
                // it keeps (the game's Lua calls it by name, .NET through the interface).
                var face = family.Interface.Name;
                if (method.DeclaredAccessibility == Accessibility.Public && !method.IsStatic && SameParameters(method, reaction))
                {
                    return "is not " + face + "'s reaction here, as " + type.Name + " gets " + face + " from a base class: list " + face + " among " + type.Name + "'s own bases too";
                }

                var shape = "a reaction of " + face + " is public, not static, and takes " + Takes(reaction);
                return family.LuaByName
                    ? "is not called on .NET, while the game's Lua calls it by its name, so the two disagree: " + shape
                    : "never runs: " + shape;
            }

            // The rest is only for methods shaped like a reaction of some interface.
            var shaped = families.Where(f => f.Shaped(method)).ToList();
            if (shaped.Count == 0)
            {
                return null;
            }

            var renamed = implemented
                .Where(f => f.RenamedNames.ContainsKey(name))
                .Select(f => f.Interface.Name + "'s reaction of that stage is " + f.RenamedNames[name])
                .ToList();
            if (renamed.Count > 0)
            {
                return "never runs: " + string.Join(", and ", renamed) + " since Moonwell 0.3";
            }

            // A forgotten interface; an abstract class may be writing reactions for subclasses that list it.
            if (!type.IsAbstract)
            {
                foreach (var family in shaped)
                {
                    if (family.Reactions.Any(r => r.Name == name))
                    {
                        return family.Hosts(type)
                            ? "never runs: it is a reaction of " + family.Interface.Name + ", which this class does not implement"
                            : "never runs: the " + family.Package + " calls " + family.Interface.Name + " only on " + family.HostsText;
                    }
                }
            }

            // A one-letter slip (a letter missing, extra, changed or two swapped) in a public method of a class that has
            // reactions; a helper of another name, or a private one, is left alone.
            if (method.DeclaredAccessibility != Accessibility.Public)
            {
                return null;
            }

            var near = implemented
                .Where(f => f.Shaped(method))
                .SelectMany(f => f.Reactions.Select(r => (Family: f, Name: r.Name, Distance: Distance(name, r.Name))))
                .OrderBy(candidate => candidate.Distance)
                .FirstOrDefault();
            if (near.Family != null && near.Distance <= 1)
            {
                return "is not a reaction of " + near.Family.Interface.Name + ", so it never runs; did you mean " + near.Name + "?";
            }

            return null;
        }

        private static bool SameParameters(IMethodSymbol method, IMethodSymbol reaction) =>
            method.Parameters.Length == reaction.Parameters.Length
            && method.Parameters.Zip(reaction.Parameters, (a, b) => SymbolEqualityComparer.Default.Equals(a.Type, b.Type)).All(same => same);

        // What a reaction takes: "a Hit", or "(Mouse, MouseButton)".
        private static string Takes(IMethodSymbol reaction) =>
            reaction.Parameters.Length == 1
                ? "a " + reaction.Parameters[0].Type.Name
                : "(" + string.Join(", ", reaction.Parameters.Select(p => p.Type.Name)) + ")";

        /// <summary>Reports a reaction interface on a class the package never calls it on.</summary>
        private void CheckHosts(SymbolAnalysisContext context, INamedTypeSymbol type)
        {
            foreach (var i in type.Interfaces)
            {
                var family = families.FirstOrDefault(f => SymbolEqualityComparer.Default.Equals(f.Interface, i));
                if (family == null || family.Hosts(type))
                {
                    continue;
                }

                var location = BaseTypeLocation(type, i) ?? type.Locations[0];
                context.ReportDiagnostic(Diagnostic.Create(Rules.UnseenReaction, location, i.Name,
                    "on this class never runs: the " + family.Package + " calls " + i.Name + " only on " + family.HostsText));
            }
        }

        /// <summary>Whether the method is the class's implementation of a reaction of an interface it implements.</summary>
        private static bool Implements(INamedTypeSymbol type, List<Family> implemented, IMethodSymbol method)
        {
            foreach (var family in implemented)
            {
                foreach (var reaction in family.Reactions)
                {
                    if (SymbolEqualityComparer.Default.Equals(type.FindImplementationForInterfaceMember(reaction), method))
                    {
                        return true;
                    }
                }
            }

            return false;
        }

        /// <summary>
        /// MW0041: a method of a map class with the name of a reaction (a virtual method) of a Moonwell class above it,
        /// which is not its override: one with the same parameters hides it, and one named On... with other parameters
        /// is a helper Moonwell takes for the reaction by its name.
        /// </summary>
        public void CheckHidden(SymbolAnalysisContext context)
        {
            if (context.Symbol is not IMethodSymbol { MethodKind: MethodKind.Ordinary, IsOverride: false } method
                || method.ContainingType is not { TypeKind: TypeKind.Class } type || !method.Locations.Any(location => location.IsInSource))
            {
                return;
            }

            var reactions = new List<IMethodSymbol>();
            for (var above = type.BaseType; above != null && reactions.Count == 0; above = above.BaseType)
            {
                reactions.AddRange(above.GetMembers(method.Name).OfType<IMethodSymbol>().Where(IsMoonwellReaction));
            }

            if (reactions.Count == 0)
            {
                return;
            }

            var hidden = reactions.FirstOrDefault(r => SameParameters(method, r));
            if (hidden != null)
            {
                var root = Root(hidden);
                context.ReportDiagnostic(Diagnostic.Create(Rules.HiddenReaction, method.Locations[0], method.Name,
                    "never runs: it hides " + root.ContainingType.Name + "." + root.Name + " instead of overriding it; write " + Signature(root, "override")));
                return;
            }

            if (method.Name.Length > 2 && method.Name.StartsWith("On", StringComparison.Ordinal) && char.IsUpper(method.Name[2]))
            {
                var root = Root(reactions[0]);
                context.ReportDiagnostic(Diagnostic.Create(Rules.HiddenReaction, method.Locations[0], method.Name,
                    "is not the reaction " + root.ContainingType.Name + "." + root.Name + "(" + Parameters(root) + "), which takes other parameters, so it never runs as one, and on .NET it makes adding the class fail; give the helper another name"));
            }
        }

        // A virtual or abstract method (or an override of one) first declared by a Moonwell assembly.
        private static bool IsMoonwellReaction(IMethodSymbol method) =>
            (method.IsVirtual || method.IsAbstract || method.IsOverride)
            && method.DeclaredAccessibility is Accessibility.Public or Accessibility.Protected or Accessibility.ProtectedOrInternal
            && Root(method).ContainingAssembly?.Name is { } assembly && (assembly == "Moonwell" || assembly.StartsWith("Moonwell.", StringComparison.Ordinal));

        private static IMethodSymbol Root(IMethodSymbol method)
        {
            while (method.OverriddenMethod != null)
            {
                method = method.OverriddenMethod;
            }

            return method;
        }

        // How to write an override of a reaction: "public override void OnDamaged(Damage damage)".
        private static string Signature(IMethodSymbol reaction, string modifier)
        {
            var access = reaction.DeclaredAccessibility == Accessibility.Protected ? "protected" : "public";
            var returns = reaction.ReturnsVoid ? "void" : reaction.ReturnType.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
            return access + " " + modifier + " " + returns + " " + reaction.Name + "(" + Parameters(reaction) + ")";
        }

        private static readonly SymbolDisplayFormat ParameterFormat = SymbolDisplayFormat.MinimallyQualifiedFormat
            .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

        private static string Parameters(IMethodSymbol method) =>
            string.Join(", ", method.Parameters.Select(p => p.Type.ToDisplayString(ParameterFormat) + " " + p.Name));

        /// <summary>Where the class lists an interface among its bases.</summary>
        private static Location? BaseTypeLocation(INamedTypeSymbol type, INamedTypeSymbol i)
        {
            foreach (var reference in type.DeclaringSyntaxReferences)
            {
                if (reference.GetSyntax() is ClassDeclarationSyntax { BaseList: { } bases })
                {
                    var written = bases.Types.FirstOrDefault(b => b.Type.ToString() == i.Name || b.Type.ToString().EndsWith("." + i.Name, StringComparison.Ordinal));
                    if (written != null)
                    {
                        return written.Type.GetLocation();
                    }
                }
            }

            return null;
        }

        /// <summary>The number of slips that turn one name into another: a letter added, removed or changed, or two next to each other swapped.</summary>
        private static int Distance(string a, string b)
        {
            var d = new int[a.Length + 1, b.Length + 1];
            for (var i = 0; i <= a.Length; i++)
            {
                d[i, 0] = i;
            }

            for (var j = 0; j <= b.Length; j++)
            {
                d[0, j] = j;
            }

            for (var i = 1; i <= a.Length; i++)
            {
                for (var j = 1; j <= b.Length; j++)
                {
                    var change = a[i - 1] == b[j - 1] ? 0 : 1;
                    d[i, j] = Math.Min(Math.Min(d[i - 1, j] + 1, d[i, j - 1] + 1), d[i - 1, j - 1] + change);
                    if (i > 1 && j > 1 && a[i - 1] == b[j - 2] && a[i - 2] == b[j - 1])
                    {
                        d[i, j] = Math.Min(d[i, j], d[i - 2, j - 2] + 1);
                    }
                }
            }

            return d[a.Length, b.Length];
        }

        private static void Report(SymbolAnalysisContext context, IMethodSymbol method, string name, string why)
        {
            context.ReportDiagnostic(Diagnostic.Create(Rules.UnseenReaction, method.Locations[0], name, why));
        }
    }
}
