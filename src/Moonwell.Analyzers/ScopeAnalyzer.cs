using System;
using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace Moonwell.Analyzers;

/// <summary>
/// Rejects a player given where a scope goes (MW0043): a player lasts the whole game, so it is no scope to make things in,
/// and a player there is most often meant as the owner, which <c>Gizmo.Create</c> and <c>Missile.Create</c> take after the
/// scope. It checks the <c>scope</c> argument of Moonwell's methods (<c>Create</c>, <c>Fire</c>, <c>Interact</c>) and what a
/// scope's <c>After</c> and <c>Every</c> are called on. A player held in a variable typed <c>Scope</c> is not seen.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class ScopeAnalyzer : DiagnosticAnalyzer
{
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => Rules.Scopes;

    public override void Initialize(AnalysisContext context)
    {
        // CSharp.lua compiles a map file that looks generated (Hud.g.cs, an <auto-generated> header) like any other.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterOperationAction(Call, OperationKind.Invocation);
    }

    private static void Call(OperationAnalysisContext context)
    {
        var call = (IInvocationOperation)context.Operation;
        var method = call.TargetMethod;
        if (!IsMoonwell(method.ContainingAssembly))
        {
            return;
        }

        if (call.Instance != null && (method.Name == "After" || method.Name == "Every") && IsMoonwellType(method.ContainingType, "Scope"))
        {
            var receiver = Unconverted(call.Instance);
            if (IsMoonwellType(receiver.Type, "Player"))
            {
                context.ReportDiagnostic(Diagnostic.Create(Rules.PlayerScope, receiver.Syntax.GetLocation(), receiver.Syntax.ToString()));
            }
        }

        foreach (var argument in call.Arguments)
        {
            if (argument.Parameter is { Name: "scope" } parameter && IsMoonwellType(parameter.Type, "Scope"))
            {
                var value = Unconverted(argument.Value);
                if (IsMoonwellType(value.Type, "Player"))
                {
                    context.ReportDiagnostic(Diagnostic.Create(Rules.PlayerScope, value.Syntax.GetLocation(), value.Syntax.ToString()));
                }
            }
        }
    }

    /// <summary>The value under the implicit conversions the compiler adds, as from a Player to the Scope it is.</summary>
    private static IOperation Unconverted(IOperation operation)
    {
        while (operation is IConversionOperation { IsImplicit: true } conversion)
        {
            operation = conversion.Operand;
        }

        return operation;
    }

    private static bool IsMoonwellType(ITypeSymbol? type, string name) =>
        type != null && type.Name == name && type.ContainingNamespace?.ToDisplayString() == "Moonwell";

    private static bool IsMoonwell(IAssemblySymbol? assembly) =>
        assembly?.Name is { } name && (name == "Moonwell" || name.StartsWith("Moonwell.", StringComparison.Ordinal));
}
