using System.Globalization;
using System.Text;
using War3Net.Build.Environment;

namespace Moonwell.Build
{
    /// <summary>
    /// Writes World Editor's places for the packages that read them as C# files in the project's generated folder: the map's
    /// regions, from <c>war3map.w3r</c>, for <c>Moonwell.Areas</c>, and the map's cameras, from <c>war3map.w3c</c>, for <c>Moonwell.Input</c>.
    /// </summary>
    public static class PlaceWriter
    {
        private const string AreaFileName = "AreaData.g.cs";

        private const string InputFileName = "InputData.g.cs";

        /// <summary>
        /// Writes <c>AreaData.g.cs</c> into the project's generated folder: <c>Moonwell.Generated.AreaData</c> with the regions' names
        /// from <c>Names()</c> and four floats each (left, bottom, right, top) from <c>Rects()</c>, in <c>war3map.w3r</c>'s order.
        /// Both are methods so that CSharp.lua writes each array once. A map with no <c>war3map.w3r</c> writes empty arrays.
        /// </summary>
        /// <param name="project">The map project.</param>
        /// <param name="regions">The map's regions; null when it has no <c>war3map.w3r</c>.</param>
        /// <returns>The path of the written file.</returns>
        /// <exception cref="BuildException">Two regions have the same name.</exception>
        public static string WriteAreas(MapProject project, MapRegions? regions)
        {
            var list = regions?.Regions ?? new List<Region>();
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var region in list)
            {
                if (!seen.Add(region.Name))
                {
                    throw new BuildException($"war3map.w3r has two regions named '{region.Name}'; a region is found by its name, so each needs its own");
                }
            }

            var names = new List<string>();
            var rects = new List<string>();
            foreach (var region in list)
            {
                names.Add(Quoted(region.Name));
                rects.Add(Literal(region.Left));
                rects.Add(Literal(region.Bottom));
                rects.Add(Literal(region.Right));
                rects.Add(Literal(region.Top));
            }

            Directory.CreateDirectory(project.GeneratedFolder);
            var path = Path.Combine(project.GeneratedFolder, AreaFileName);
            var text = string.Join(
                "\n",
                "// Generated by Moonwell's build from war3map.w3r. Do not edit; every build writes it anew.",
                "namespace Moonwell.Generated",
                "{",
                "    public static class AreaData",
                "    {",
                "        public static string[] Names() => " + ArrayOf("string", names) + ";",
                "        public static float[] Rects() => " + ArrayOf("float", rects) + ";",
                "    }",
                "}",
                string.Empty);
            File.WriteAllText(path, text);
            return path;
        }

        /// <summary>Removes the file an earlier build wrote, which a map that no longer references <c>Moonwell.Areas</c> would not compile.</summary>
        /// <param name="project">The map project.</param>
        public static void DeleteAreas(MapProject project)
        {
            var path = Path.Combine(project.GeneratedFolder, AreaFileName);
            if (File.Exists(path))
            {
                File.Delete(path);
            }
        }

        /// <summary>
        /// Writes <c>InputData.g.cs</c> into the project's generated folder: <c>Moonwell.Generated.InputData</c> with whether the map
        /// uses the mouse (<c>Mouse</c>), the cameras' names from <c>CameraNames()</c> and their numbers from <c>Cameras()</c>, in
        /// <c>war3map.w3c</c>'s order. Per camera the numbers are: the target's x and y, the count n, n pairs of a field code and its
        /// value, and the camera type (-1 when the file's format has none). The pairs are the <c>CameraSetupSetField</c> calls of World
        /// Editor's own script, as War3Net writes them and under the same format conditions. A map with no <c>war3map.w3c</c> writes
        /// empty arrays.
        /// </summary>
        /// <param name="project">The map project.</param>
        /// <param name="cameras">The map's cameras; null when it has no <c>war3map.w3c</c>.</param>
        /// <param name="mouse">Whether the map's code names the mouse, so that the package listens for it.</param>
        /// <returns>The path of the written file.</returns>
        /// <exception cref="BuildException">Two cameras have the same name.</exception>
        public static string WriteInput(MapProject project, MapCameras? cameras, bool mouse)
        {
            var list = cameras?.Cameras ?? new List<Camera>();
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var camera in list)
            {
                if (!seen.Add(camera.Name))
                {
                    throw new BuildException($"war3map.w3c has two cameras named '{camera.Name}'; a camera is found by its name, so each needs its own");
                }
            }

            var names = new List<string>();
            var numbers = new List<string>();
            foreach (var camera in list)
            {
                names.Add(Quoted(camera.Name));
                AddCamera(numbers, camera, cameras!);
            }

            Directory.CreateDirectory(project.GeneratedFolder);
            var path = Path.Combine(project.GeneratedFolder, InputFileName);
            var text = string.Join(
                "\n",
                "// Generated by Moonwell's build from war3map.w3c and the map's code. Do not edit; every build writes it anew.",
                "namespace Moonwell.Generated",
                "{",
                "    public static class InputData",
                "    {",
                "        public const bool Mouse = " + (mouse ? "true" : "false") + ";",
                "        public static string[] CameraNames() => " + ArrayOf("string", names) + ";",
                "        public static float[] Cameras() => " + ArrayOf("float", numbers) + ";",
                "    }",
                "}",
                string.Empty);
            File.WriteAllText(path, text);
            return path;
        }

        /// <summary>Removes the file an earlier build wrote, which a map that no longer references <c>Moonwell.Input</c> would not compile.</summary>
        /// <param name="project">The map project.</param>
        public static void DeleteInput(MapProject project)
        {
            var path = Path.Combine(project.GeneratedFolder, InputFileName);
            if (File.Exists(path))
            {
                File.Delete(path);
            }
        }

        // One camera's numbers: the pairs follow War3Net's MapScriptBuilder.GenerateCreateCameras, which writes what World Editor's own
        // script does; the codes are Moonwell's own (0 distance, 1 far Z, 2 angle of attack, 3 field of view, 4 roll, 5 rotation, 6 Z offset,
        // 7 near Z, 8 local pitch, 9 local yaw, 10 local roll, 11 depth-of-field distance, 12 depth-of-field scale, 13 Z absolute).
        private static void AddCamera(List<string> numbers, Camera camera, MapCameras file)
        {
            var pairs = new List<(int Code, float Value)>
            {
                (6, camera.ZOffset),
                (5, camera.Rotation),
                (2, camera.AngleOfAttack),
                (0, camera.TargetDistance),
                (4, camera.Roll),
                (3, camera.FieldOfView),
                (1, camera.FarClippingPlane),
            };
            if (file.UseNewFormat)
            {
                pairs.Add((7, camera.NearClippingPlane));
                pairs.Add((8, camera.LocalPitch));
                pairs.Add((9, camera.LocalYaw));
                pairs.Add((10, camera.LocalRoll));
            }

            var v3 = file.FormatVersion >= MapCamerasFormatVersion.v3;
            if (v3)
            {
                pairs.Add((11, camera.DofDistance));
                pairs.Add((12, camera.DofScale));
                pairs.Add((13, camera.PosAbsoluteZ));
            }

            numbers.Add(Literal(camera.TargetPosition.X));
            numbers.Add(Literal(camera.TargetPosition.Y));
            numbers.Add(Literal(pairs.Count));
            foreach (var (code, value) in pairs)
            {
                numbers.Add(Literal(code));
                numbers.Add(Literal(value));
            }

            numbers.Add(Literal(v3 ? camera.CameraType : -1));
        }

        // An empty array needs its type spelled out.
        private static string ArrayOf(string type, List<string> items)
        {
            return items.Count == 0 ? "new " + type + "[0]" : "new[] { " + string.Join(", ", items) + " }";
        }

        // A C# string literal: quotes, backslashes and control characters escaped.
        private static string Quoted(string name)
        {
            var text = new StringBuilder(name.Length + 2);
            text.Append('"');
            foreach (var c in name)
            {
                switch (c)
                {
                    case '"':
                        text.Append("\\\"");
                        break;
                    case '\\':
                        text.Append("\\\\");
                        break;
                    case '\n':
                        text.Append("\\n");
                        break;
                    case '\r':
                        text.Append("\\r");
                        break;
                    case '\t':
                        text.Append("\\t");
                        break;
                    default:
                        if (char.IsControl(c))
                        {
                            text.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                        }
                        else
                        {
                            text.Append(c);
                        }

                        break;
                }
            }

            text.Append('"');
            return text.ToString();
        }

        private static string Literal(float value)
        {
            return value.ToString("R", CultureInfo.InvariantCulture) + "f";
        }
    }
}
