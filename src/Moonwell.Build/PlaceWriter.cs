using System.Globalization;
using System.Text;
using War3Net.Build.Environment;

namespace Moonwell.Build
{
    /// <summary>
    /// Writes World Editor's places for the packages that read them as C# files in the project's generated folder: the map's
    /// regions, from <c>war3map.w3r</c>, for <c>Moonwell.Areas</c>.
    /// </summary>
    public static class PlaceWriter
    {
        private const string AreaFileName = "AreaData.g.cs";

        /// <summary>
        /// Writes <c>AreaData.g.cs</c> into the project's generated folder: <c>Moonwell.Generated.AreaData</c> with the regions' names
        /// from <c>Names()</c> and four floats each (left, bottom, right, top) from <c>Rects()</c>, in <c>war3map.w3r</c>'s order.
        /// Both are methods so that CSharp.lua writes each array once. A map with no <c>war3map.w3r</c> writes empty arrays.
        /// </summary>
        /// <param name="project">The map project.</param>
        /// <param name="regions">The map's regions; null when it has no <c>war3map.w3r</c>.</param>
        /// <returns>The path of the written file.</returns>
        /// <exception cref="BuildException">Two regions have the same name.</exception>
        public static string WriteAreas(MapProject project, MapRegions? regions)
        {
            var list = regions?.Regions ?? new List<Region>();
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var region in list)
            {
                if (!seen.Add(region.Name))
                {
                    throw new BuildException($"war3map.w3r has two regions named '{region.Name}'; a region is found by its name, so each needs its own");
                }
            }

            var names = new List<string>();
            var rects = new List<string>();
            foreach (var region in list)
            {
                names.Add(Quoted(region.Name));
                rects.Add(Literal(region.Left));
                rects.Add(Literal(region.Bottom));
                rects.Add(Literal(region.Right));
                rects.Add(Literal(region.Top));
            }

            Directory.CreateDirectory(project.GeneratedFolder);
            var path = Path.Combine(project.GeneratedFolder, AreaFileName);
            var text = string.Join(
                "\n",
                "// Generated by Moonwell's build from war3map.w3r. Do not edit; every build writes it anew.",
                "namespace Moonwell.Generated",
                "{",
                "    public static class AreaData",
                "    {",
                "        public static string[] Names() => " + ArrayOf("string", names) + ";",
                "        public static float[] Rects() => " + ArrayOf("float", rects) + ";",
                "    }",
                "}",
                string.Empty);
            File.WriteAllText(path, text);
            return path;
        }

        /// <summary>Removes the file an earlier build wrote, which a map that no longer references <c>Moonwell.Areas</c> would not compile.</summary>
        /// <param name="project">The map project.</param>
        public static void DeleteAreas(MapProject project)
        {
            var path = Path.Combine(project.GeneratedFolder, AreaFileName);
            if (File.Exists(path))
            {
                File.Delete(path);
            }
        }

        // An empty array needs its type spelled out.
        private static string ArrayOf(string type, List<string> items)
        {
            return items.Count == 0 ? "new " + type + "[0]" : "new[] { " + string.Join(", ", items) + " }";
        }

        // A C# string literal: quotes, backslashes and control characters escaped.
        private static string Quoted(string name)
        {
            var text = new StringBuilder(name.Length + 2);
            text.Append('"');
            foreach (var c in name)
            {
                switch (c)
                {
                    case '"':
                        text.Append("\\\"");
                        break;
                    case '\\':
                        text.Append("\\\\");
                        break;
                    case '\n':
                        text.Append("\\n");
                        break;
                    case '\r':
                        text.Append("\\r");
                        break;
                    case '\t':
                        text.Append("\\t");
                        break;
                    default:
                        if (char.IsControl(c))
                        {
                            text.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                        }
                        else
                        {
                            text.Append(c);
                        }

                        break;
                }
            }

            text.Append('"');
            return text.ToString();
        }

        private static string Literal(float value)
        {
            return value.ToString("R", CultureInfo.InvariantCulture) + "f";
        }
    }
}
