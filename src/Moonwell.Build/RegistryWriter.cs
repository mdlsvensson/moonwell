using System.Text;

namespace Moonwell.Build
{
    /// <summary>Writes the C# file that registers the map's object classes with their object ids when the runtime starts.</summary>
    public static class RegistryWriter
    {
        private const string CarrierSuffix = "#carrier";
        private const string Types = "global::Moonwell.ObjectTypes";

        /// <summary>
        /// Writes <c>ObjectRegistry.g.cs</c> into the project's generated folder: <c>Moonwell.Generated.ObjectRegistry.Register()</c>
        /// gives each used class that has an object its id (a declared class its own, a standard class its standard id), then
        /// registers how units, items, destructables and abilities of each are made, and each declared buff's display. A
        /// <c>[Replaces]</c> class is made at the standard id instead of the standard class, which keeps the id only.
        /// </summary>
        /// <param name="project">The map project.</param>
        /// <param name="used">The used classes.</param>
        /// <param name="declared">The declared objects.</param>
        /// <param name="ids">The object id of each declared class, and of each buff's carrier as <c>&lt;class&gt;#carrier</c>.</param>
        /// <returns>The path of the written file.</returns>
        /// <exception cref="BuildException">A declared class or a buff's carrier has no id.</exception>
        public static string Write(MapProject project, IReadOnlyList<UsedClass> used, IReadOnlyList<DeclaredObject> declared, IReadOnlyDictionary<string, string> ids)
        {
            var objects = declared.ToDictionary(one => one.ClassName, StringComparer.Ordinal);
            var replaced = new HashSet<string>(StringComparer.Ordinal);
            foreach (var one in used)
            {
                if (objects.TryGetValue(one.FullName, out var replacing) && replacing.Replaces)
                {
                    replaced.Add(one.BaseFullName);
                }
            }

            // The ids come first: a constructor that a registration below runs may ask for the id of any class.
            var idLines = new List<string>();
            var makerLines = new List<string>();
            foreach (var one in used.OrderBy(one => one.FullName, StringComparer.Ordinal))
            {
                string id;
                if (objects.ContainsKey(one.FullName))
                {
                    id = IdOf(ids, one.FullName);
                }
                else if (one.StandardId != null)
                {
                    id = one.StandardId;
                }
                else
                {
                    continue;
                }

                var type = "global::" + one.FullName;
                idLines.Add($"{Types}.Id<{type}>({FourCC(id)});");
                var maker = MakerOf(one.Kind);
                if (maker != null && !replaced.Contains(one.FullName))
                {
                    makerLines.Add($"{Types}.{maker}<{type}>({FourCC(id)}, () => new {type}());");
                }

                if (one.Kind == "buff" && objects.ContainsKey(one.FullName))
                {
                    makerLines.Add($"{Types}.BuffDisplay<{type}>({FourCC(id)}, {FourCC(IdOf(ids, one.FullName + CarrierSuffix))});");
                }
            }

            var text = new StringBuilder();
            text.Append("// Generated by Moonwell's build. Do not edit; every build writes it anew.\n");
            text.Append("namespace Moonwell.Generated\n");
            text.Append("{\n");
            text.Append("    /// <summary>Registers the object classes the map uses with their object ids.</summary>\n");
            text.Append("    public static class ObjectRegistry\n");
            text.Append("    {\n");
            text.Append("        /// <summary>Runs first when the runtime starts, before the map's components are added.</summary>\n");
            text.Append("        public static void Register()\n");
            text.Append("        {\n");
            foreach (var line in idLines.Concat(makerLines))
            {
                text.Append("            ").Append(line).Append('\n');
            }

            text.Append("        }\n");
            text.Append("    }\n");
            text.Append("}\n");

            Directory.CreateDirectory(project.GeneratedFolder);
            var path = Path.Combine(project.GeneratedFolder, "ObjectRegistry.g.cs");
            File.WriteAllText(path, text.ToString());
            return path;
        }

        private static string? MakerOf(string kind)
        {
            switch (kind)
            {
                case "unit":
                case "hero":
                    return "Unit";
                case "item":
                    return "Item";
                case "destructable":
                    return "Destructable";
                case "ability":
                    return "Ability";
                default:
                    return null;
            }
        }

        private static string IdOf(IReadOnlyDictionary<string, string> ids, string name)
        {
            return ids.TryGetValue(name, out var id) ? id : throw new BuildException($"{name} has no object id");
        }

        private static string FourCC(string id)
        {
            return $"{Types}.FourCC({ObjectLua.Quote(id)})";
        }
    }
}
