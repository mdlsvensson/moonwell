namespace Moonwell.Build
{
    /// <summary>Writes the C# file that gives the map its <c>Main</c>.</summary>
    public static class EntryWriter
    {
        /// <summary>Writes <c>MapMain.g.cs</c> for a map with no object registry: <c>Main</c> starts the runtime with the map alone.</summary>
        /// <param name="project">The map project.</param>
        /// <param name="settings">The settings read from the map class, which name the class to start.</param>
        /// <returns>The path of the written file.</returns>
        public static string Write(MapProject project, MapSettings settings)
        {
            return Write(project, settings, false);
        }

        /// <summary>Writes <c>MapMain.g.cs</c> into the project's generated folder.</summary>
        /// <param name="project">The map project.</param>
        /// <param name="settings">The settings read from the map class, which name the class to start.</param>
        /// <param name="registry">True starts the runtime with <c>ObjectRegistry.Register</c>, which <see cref="RegistryWriter"/> writes.</param>
        /// <returns>The path of the written file.</returns>
        public static string Write(MapProject project, MapSettings settings, bool registry)
        {
            Directory.CreateDirectory(project.GeneratedFolder);
            var path = Path.Combine(project.GeneratedFolder, "MapMain.g.cs");
            var start = registry
                ? "global::Moonwell.Runtime.Start(new global::" + settings.TypeName + "(), global::Moonwell.Generated.ObjectRegistry.Register);"
                : "global::Moonwell.Runtime.Start(new global::" + settings.TypeName + "());";
            var text = string.Join(
                "\n",
                "// Generated by Moonwell's build. Do not edit; every build writes it anew.",
                "namespace Moonwell.Generated",
                "{",
                "    public static class MapMain",
                "    {",
                "        public static void Main()",
                "        {",
                "            " + start,
                "        }",
                "    }",
                "}",
                string.Empty);
            File.WriteAllText(path, text);
            return path;
        }
    }
}
