import type { Natives } from "../natives/natives.ts";
import { CATEGORIES } from "../objectdata/metadata.ts";
import type { ResolvedObject } from "../objectdata/resolve.ts";

const LUA_TYPES: Record<string, string> = {
  integer: "integer",
  real: "number",
  boolean: "boolean",
  string: "string",
  code: "function",
};

const LUA_KEYWORDS = new Set([
  "and",
  "break",
  "do",
  "else",
  "elseif",
  "end",
  "false",
  "for",
  "function",
  "goto",
  "if",
  "in",
  "local",
  "nil",
  "not",
  "or",
  "repeat",
  "return",
  "then",
  "true",
  "until",
  "while",
]);

/** The LuaLS type for a JASS type (spec §3.4). Handle types, and Lua types from the Lua extras, pass through. */
export function luaType(jassType: string): string {
  return LUA_TYPES[jassType] ?? jassType;
}

/** A JASS parameter name as a Lua identifier: Lua keywords get a trailing underscore. */
function paramName(name: string): string {
  return LUA_KEYWORDS.has(name) ? `${name}_` : name;
}

/** Handle classes, each after its parent, starting from `handle` (declared by no `type` line). */
function classLines(natives: Natives): string[] {
  const children = new Map<string, string[]>();
  for (const type of natives.types) children.set(type.extends, [...(children.get(type.extends) ?? []), type.name]);
  const lines = ["---@class handle"];
  const visit = (parent: string) => {
    for (const name of (children.get(parent) ?? []).sort()) {
      lines.push(`---@class ${name}: ${parent}`);
      visit(name);
    }
  };
  visit("handle");
  return lines;
}

/** .moonwell/types/natives.d.lua (spec §4.2). */
export function renderNativesDeclarations(natives: Natives): string {
  const out = [
    "---@meta",
    `-- GENERATED by Moonwell from Warcraft III ${natives.gameVersion} (common.j, blizzard.j); do not edit.`,
    "",
    ...classLines(natives),
    "",
  ];
  for (const fn of natives.functions) {
    for (const param of fn.params) out.push(`---@param ${paramName(param.name)} ${luaType(param.type)}`);
    if (fn.returns !== "nothing") out.push(`---@return ${luaType(fn.returns)}`);
    out.push(`function ${fn.name}(${fn.params.map((param) => paramName(param.name)).join(", ")}) end`, "");
  }
  for (const global of natives.globals) {
    out.push(`---@type ${luaType(global.type)}${global.array ? "[]" : ""}`, `${global.name} = nil`, "");
  }
  return out.join("\n");
}

