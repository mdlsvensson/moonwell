/** .moonwell/types/objects.d.lua: `src/generated/objects.yue` as gameplay code sees it (spec §4.2). */
export function renderObjectDeclarations(objects: Pick<ResolvedObject, "category" | "key" | "id">[]): string {
  const out = [
    "---@meta generated.objects",
    // `objects.units = {}` below would otherwise warn that the class's fields are missing.
    "---@diagnostic disable: missing-fields",
    "-- GENERATED by Moonwell from objects/**.pkl; do not edit.",
    "",
  ];
  for (const category of CATEGORIES) {
    out.push(`---@class generated.objects.${category}`);
    const entries = objects.filter((object) => object.category === category)
      .sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : 0);
    for (const { key, id } of entries) out.push(`---@field ${key} integer ${id}`);
    out.push("");
  }
  out.push("local objects = {}", "");
  for (const category of CATEGORIES) {
    out.push(`---@type generated.objects.${category}`, `objects.${category} = {}`, "");
  }
  out.push("return objects", "");
  return out.join("\n");
}
